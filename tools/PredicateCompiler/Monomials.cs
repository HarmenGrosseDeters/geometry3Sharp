// Predicate compiler, the monomial pass: exact sign predicates on double coordinates of any exponent
// (docs/design/EXACT_FALLBACK_MONOMIALS.md). It reads 'dpredicate' entries (doubles.spec), whose formula is a
// homogeneous polynomial of degree d in the input coordinates (the determinant with a column of ones, so no
// differences of inputs are needed), and generates for each a kernel without floating-point arithmetic:
//
//   Input model: every finite double is v = m 2^e with an integer |m| <= 2^53 - 1 and e in [-1074, 971] (a subnormal
//   has e = -1074). The kernel reads m and e from the bits.
//   Monomial rule: the sign expression is expanded into its monomials over the inputs, like terms merged (the
//   expansion of the graph with the value rule's operations, exact integer coefficients). The pass requires every
//   monomial to have the same degree d and the coefficient +1 or -1.
//   Value rule per monomial: |m_1 ... m_d| <= (2^53 - 1)^d < 2^(53 d), so d limbs of 64 bits.
//   Accumulator rule: with emin and emax the smallest and largest exponent of the nonzero inputs of a call and
//   s = emax - emin, a monomial is its mantissa product times 2^(e_1 + ... + e_d), an integer multiple of 2^(d emin)
//   shifted left by at most d s bits. The positive and the negative monomials are added into two magnitude
//   accumulators in units of 2^(d emin). Each accumulator is below T (2^53 - 1)^d 2^(d s) < 2^(d s + 53 d + g) with T
//   the number of monomials and g = ceil(log2 T), so
//       L(s) = floor(d s / 64) + ceil((53 d + g + 63) / 64) limbs
//   hold it: a monomial is written to d + 1 limbs from limb floor(offset / 64), offset <= d s, which is inside L(s)
//   (checked by Analyze: ceil((53 d + g + 63) / 64) >= d + 1), and the sum never carries out of the top limb. The sign
//   of the predicate is the comparison of the two accumulators from the top limb.
//   The worst case is s = 2045 (emin = -1074, emax = 971).
//
// The generated code has no floating-point operation, so no rounding, no overflow or underflow and no FMA question,
// and it allocates nothing (two stackalloc'ed accumulators). GeneratedDoublePredicatesTests keeps the checked-in file
// and the table of the design doc equal to this derivation and checks the limb rule with exact integers for every s.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Numerics;
using System.Text;

namespace G3PredicateCompiler
{
    /// <summary> a 'dpredicate' with its monomials and the accumulator's bounds </summary>
    public sealed class MonomialPredicate
    {
        public Predicate Source;
        public string Name => Source.Name;
        /// <summary> the inputs in parameter order: point by point, each with the components of DoubleComps </summary>
        public List<string> Inputs = new List<string>();
        public int Degree;
        /// <summary> the monomials: the indices of their d inputs (sorted, an input may repeat) and the sign </summary>
        public List<(int[] inputs, int sign)> Monomials = new List<(int[] inputs, int sign)>();
        /// <summary> g = ceil(log2(number of monomials)) </summary>
        public int GuardBits;
        /// <summary> ceil((53 d + g + 63) / 64): the accumulator has floor(d s / 64) + ExtraLimbs limbs </summary>
        public int ExtraLimbs;
        public int Limbs(int span) => Degree * span / 64 + ExtraLimbs;
    }

    public static class MonomialPass
    {
        /// <summary> the largest exponent span of two finite doubles: 971 - (-1074) </summary>
        public const int MaxSpan = 2045;
        public const int MantissaBits = 53;
        public const string TableBegin = "<!-- generated by tools/PredicateCompiler --dtable; do not edit -->";
        public const string TableEnd = "<!-- end of the generated monomial table -->";
        static string inv(int v) => v.ToString(CultureInfo.InvariantCulture);

        /// <summary> the 'dpredicate' entries of a spec with their monomials and bounds </summary>
        public static List<MonomialPredicate> Analyze(string spec)
        {
            var result = new List<MonomialPredicate>();
            foreach (var p in PredicateCompiler.Analyze(spec)) {
                if (!p.Doubles)
                    throw new NotSupportedException($"{p.Name}: the monomial pass reads 'dpredicate' entries only");
                if (p.Signs.Count != 1)
                    throw new NotSupportedException($"{p.Name}: the monomial pass takes one sign expression");
                var mp = new MonomialPredicate { Source = p };
                foreach (var pt in p.Points)
                    foreach (char c in p.Comps)
                        mp.Inputs.Add(pt + "." + c);
                if (mp.Inputs.Count > 64)
                    throw new NotSupportedException($"{p.Name}: more than 64 inputs (the sign mask is one ulong)");
                var poly = expand(p, p.Root, new Dictionary<Node, Dictionary<string, (int[] idx, BigInteger c)>>(), mp.Inputs);
                foreach (var t in poly.Values.OrderBy(t => string.Join(",", t.idx.Select(i => i.ToString("D2", CultureInfo.InvariantCulture))), StringComparer.Ordinal)) {
                    if (t.c.IsZero) continue;
                    if (!BigInteger.Abs(t.c).IsOne)
                        throw new NotSupportedException($"{p.Name}: a monomial with the coefficient {t.c} (only +1 and -1 are generated)");
                    mp.Monomials.Add((t.idx, t.c.Sign));
                }
                if (mp.Monomials.Count == 0)
                    throw new NotSupportedException($"{p.Name}: the sign expression is identically zero");
                mp.Degree = mp.Monomials[0].inputs.Length;
                if (mp.Monomials.Any(m => m.inputs.Length != mp.Degree))
                    throw new NotSupportedException($"{p.Name}: the monomial pass needs a homogeneous formula (monomials of one degree)");
                if (mp.Degree < 2 || mp.Degree > 5)
                    throw new NotSupportedException($"{p.Name}: degree {mp.Degree} (2 to 5 are generated)");
                mp.GuardBits = (int)((BigInteger)(mp.Monomials.Count - 1)).GetBitLength();
                mp.ExtraLimbs = (MantissaBits * mp.Degree + mp.GuardBits + 63 + 63) / 64;
                // a monomial takes d limbs, shifted by less than 64 bits d + 1, written from limb floor(offset / 64)
                if (mp.ExtraLimbs < mp.Degree + 1)
                    throw new InvalidOperationException($"{p.Name}: the accumulator rule does not cover a monomial's limbs");
                result.Add(mp);
            }
            return result;
        }

        // the polynomial of a node: monomial key -> (sorted input indices, coefficient)
        static Dictionary<string, (int[] idx, BigInteger c)> expand(Predicate p, Node n,
            Dictionary<Node, Dictionary<string, (int[] idx, BigInteger c)>> memo, List<string> inputs)
        {
            if (memo.TryGetValue(n, out var done)) return done;
            var r = new Dictionary<string, (int[] idx, BigInteger c)>();
            Action<int[], BigInteger> add = (idx, c) => {
                string key = string.Join(",", idx);
                r[key] = (idx, (r.TryGetValue(key, out var old) ? old.c : BigInteger.Zero) + c);
            };
            switch (n.Op) {
                case Op.Input:
                    int i = inputs.IndexOf(n.Point + "." + n.Comp);
                    if (i < 0) throw new FormatException($"{p.Name}: unknown input {n.Point}.{n.Comp}");
                    add(new[] { i }, BigInteger.One);
                    break;
                case Op.Add: case Op.Sub:
                    foreach (var t in expand(p, n.A, memo, inputs).Values) add(t.idx, t.c);
                    foreach (var t in expand(p, n.B, memo, inputs).Values) add(t.idx, n.Op == Op.Add ? t.c : -t.c);
                    break;
                case Op.Mul:
                    foreach (var x in expand(p, n.A, memo, inputs).Values)
                        foreach (var y in expand(p, n.B, memo, inputs).Values)
                            add(x.idx.Concat(y.idx).OrderBy(k => k).ToArray(), x.c * y.c);
                    break;
            }
            foreach (var key in r.Where(kv => kv.Value.c.IsZero).Select(kv => kv.Key).ToList()) r.Remove(key);
            memo[n] = r;
            return r;
        }

        /// <summary> the bound table of the monomial predicates of a spec, as Markdown between TableBegin and TableEnd </summary>
        public static string Table(string spec)
        {
            var sb = new StringBuilder();
            sb.Append(TableBegin).Append('\n');
            sb.Append("| predicate | degree d | monomials T | guard bits g | bits of a monomial | accumulator limbs L(s), s = emax - emin | limbs at s = 0 | limbs at s = 2045 | stack bytes at s = 2045 (both accumulators) |\n");
            sb.Append("|---|---|---|---|---|---|---|---|---|\n");
            foreach (var m in Analyze(spec))
                sb.Append($"| `{m.Name}` | {inv(m.Degree)} | {inv(m.Monomials.Count)} | {inv(m.GuardBits)} | {inv(MantissaBits * m.Degree)} | `floor({inv(m.Degree)} s / 64) + {inv(m.ExtraLimbs)}` | {inv(m.Limbs(0))} | {inv(m.Limbs(MaxSpan))} | {inv(16 * m.Limbs(MaxSpan))} |\n");
            sb.Append(TableEnd).Append('\n');
            return sb.ToString();
        }

        /// <summary> the generated C# of a spec's monomial predicates (math/Generated/DoublePredicates.cs) </summary>
        public static string Code(string spec, string specPath, string outPath, string className)
        {
            var preds = Analyze(spec);
            var sb = new StringBuilder();
            // (no <auto-generated> marker: Roslyn skips such files in analyzers, and the exact-code analyzers must see it)
            sb.Append($"// Generated by tools/PredicateCompiler from {specPath}. Do not edit; regenerate with:\n");
            sb.Append($"//   dotnet run --project tools/PredicateCompiler -- --dcode {specPath} {outPath}\n");
            sb.Append("// (GeneratedDoublePredicatesTests fails when this file differs from the generator's output.)\n");
            sb.Append("// Distributed under the Boost Software License, Version 1.0. http://www.boost.org/LICENSE_1_0.txt\n");
            sb.Append("using System;\nusing System.Runtime.CompilerServices;\n\nnamespace g3\n{\n");
            sb.Append("    /// <summary>\n");
            sb.Append("    /// Exact sign predicates on double coordinates of any exponent, generated from their formulas by\n");
            sb.Append("    /// tools/PredicateCompiler (the monomial pass; docs/design/EXACT_FALLBACK_MONOMIALS.md). Every finite double is\n");
            sb.Append("    /// m 2^e with an integer |m| below 2^53. The predicate is a sum of signed monomials, each a product of d\n");
            sb.Append("    /// mantissas (below 2^(53 d): d limbs) times 2^(the sum of its exponents). The positive and the negative monomials\n");
            sb.Append("    /// are added, shifted to their exponent, into two magnitude accumulators on the stack, and the sign is the\n");
            sb.Append("    /// comparison of the two. Integer arithmetic only: no rounding, no overflow or underflow, no allocation, and no\n");
            sb.Append("    /// restriction on the coordinates other than finite (NaN and infinity throw, as in ExactPredicates).\n");
            sb.Append("    /// The limbs of the accumulators are derived per predicate (the comment of each kernel).\n");
            sb.Append("    /// </summary>\n");
            sb.Append($"    internal static unsafe class {className}\n    {{\n");
            sb.Append("        // input i of a kernel: its mantissa m[i] (below 2^53), its biased exponent e[i] (v = m 2^(e - 1075); 1 for zero and\n");
            sb.Append("        // subnormal values), its sign in bit i of neg; emin and emax over the nonzero inputs\n");
            sb.Append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]\n");
            sb.Append("        static void load(double v, int i, ulong* m, int* e, ref ulong neg, ref int emin, ref int emax)\n        {\n");
            sb.Append("            long bits = BitConverter.DoubleToInt64Bits(v);\n");
            sb.Append("            // Stryker disable once Bitwise: the sign bits an arithmetic shift brings in are masked off in the next line\n");
            sb.Append("            long top = bits >> 52;\n");
            sb.Append("            int ex = (int)(top & 0x7FF);\n");
            sb.Append("            ulong f = (ulong)bits & 0xFFFFFFFFFFFFFUL;\n");
            sb.Append("            if (ex == 0x7FF)\n                throw new ArgumentException(\"ExactPredicates: coordinates must be finite\");\n");
            sb.Append("            if (ex == 0)\n                ex = 1;\n            else\n");
            sb.Append("                // Stryker disable once Assignment: bit 52 of f is clear, so | and ^ set it alike\n");
            sb.Append("                f |= 1UL << 52;\n");
            sb.Append("            m[i] = f;\n            e[i] = ex;\n");
            sb.Append("            // Stryker disable once Equality,Assignment: bits == 0 is +0, whose sign is never read (a zero factor adds nothing); bit i of neg is set once\n");
            sb.Append("            if (bits < 0)\n                neg |= 1UL << i;\n");
            sb.Append("            if (f != 0) {\n                emin = Math.Min(emin, ex);\n                emax = Math.Max(emax, ex);\n            }\n        }\n\n");
            sb.Append("        // the sign of p - q (magnitudes of `limbs` limbs)\n");
            sb.Append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]\n");
            sb.Append("        static int compare(ulong* p, ulong* q, int limbs)\n        {\n");
            sb.Append("            for (int i = limbs - 1; i >= 0; --i)\n                if (p[i] != q[i])\n");
            sb.Append("                    // Stryker disable once Equality: reached only for p[i] != q[i]\n");
            sb.Append("                    return (p[i] > q[i]) ? 1 : -1;\n            return 0;\n        }\n");
            foreach (int d in preds.Select(p => p.Degree).Distinct().OrderBy(d => d))
                add_helper(sb, d);
            foreach (var p in preds)
                kernel(sb, p);
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        // add<d>: one monomial of degree d, m[i0] ... m[i(d-1)] 2^(e[i0] + ... - b), into p (positive) or q (negative)
        static void add_helper(StringBuilder sb, int d)
        {
            string idx = string.Join(", ", Enumerable.Range(0, d).Select(k => "int i" + inv(k)));
            sb.Append($"\n        // one monomial of degree {inv(d)}: the product of the mantissas (below 2^{inv(MantissaBits * d)}: {inv(d)} limbs), shifted left by\n");
            sb.Append("        // (the sum of the exponents) - b bits, added to p if its sign is positive and to q if negative (`minus` is the\n");
            sb.Append("        // sign of the monomial in the formula; the mantissas' signs are in neg). A zero factor adds nothing.\n");
            sb.Append("        // (internal for the tests, which check it against BigInteger on accumulators with long carries)\n");
            sb.Append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]\n");
            sb.Append($"        internal static void add{inv(d)}(ulong* p, ulong* q, int limbs, ulong* m, int* e, ulong neg, int b, {idx}, bool minus)\n        {{\n");
            sb.Append("            ulong f0 = m[i0]");
            for (int k = 1; k < d; ++k) sb.Append($", f{inv(k)} = m[i{inv(k)}]");
            sb.Append(";\n");
            sb.Append("            // (needed, not only faster: the exponent of a zero is not in emin, so its offset can lie below the accumulator)\n");
            sb.Append("            if (" + string.Join(" || ", Enumerable.Range(0, d).Select(k => $"f{inv(k)} == 0")) + ")\n                return;\n");
            // the product: r0 .. r(d-1), factor by factor
            sb.Append("            ulong lo, hi, carry;\n");
            sb.Append("            ulong r0 = f0");
            for (int k = 1; k < d; ++k) sb.Append($", r{inv(k)}");
            sb.Append(";\n");
            for (int k = 1; k < d; ++k) {
                // multiply the k limbs r0 .. r(k-1) by f_k: k + 1 limbs (no carry out: the product is below 2^(53 (k + 1)))
                sb.Append($"            hi = FixedArith.MulHigh(r0, f{inv(k)}, out r0);\n");
                sb.Append("            carry = hi;\n");
                for (int j = 1; j < k; ++j) {
                    sb.Append($"            hi = FixedArith.MulHigh(r{inv(j)}, f{inv(k)}, out lo);\n");
                    sb.Append("            lo += carry;\n");
                    sb.Append("            hi += (lo < carry) ? 1UL : 0UL;\n");
                    sb.Append($"            r{inv(j)} = lo;\n");
                    sb.Append("            carry = hi;\n");
                }
                sb.Append($"            r{inv(k)} = carry;\n");
            }
            sb.Append("            // Stryker disable once Bitwise: neg is unsigned, >> and >>> are the same\n");
            sb.Append("            ulong " + string.Join(", ", Enumerable.Range(0, d).Select(k => $"s{inv(k)} = neg >> i{inv(k)}")) + ";\n");
            sb.Append("            bool negative = (((" + string.Join(" ^ ", Enumerable.Range(0, d).Select(k => $"s{inv(k)}")) + ") & 1) != 0) != minus;\n");
            sb.Append("            // (not negative: every factor is nonzero, so its exponent is at least emin)\n");
            sb.Append("            uint off = (uint)(" + string.Join(" + ", Enumerable.Range(0, d).Select(k => $"e[i{inv(k)}]")) + " - b);\n");
            sb.Append("            uint w = off / 64;\n");
            sb.Append($"            // (the limb rule keeps the {inv(d + 1)} limbs of the shifted monomial inside the accumulator; checked all the same, so that an\n");
            sb.Append("            // error of the rule, of the generator or of a caller is an exception and not a write outside the stack buffer)\n");
            sb.Append($"            if (w + {inv(d + 1)} > (uint)limbs)\n");
            sb.Append("                throw new InvalidOperationException(\"DoublePredicates: a monomial outside its accumulator\");\n");
            sb.Append("            ulong* a = (negative ? q : p) + w;\n");
            sb.Append("            int s = (int)(off & 63);\n");
            // the shifted limbs t0 .. td
            sb.Append("            ulong t0");
            for (int k = 1; k <= d; ++k) sb.Append($", t{inv(k)}");
            sb.Append(";\n");
            sb.Append("            if (s == 0) {\n                ");
            for (int k = 0; k < d; ++k) sb.Append($"t{inv(k)} = r{inv(k)}; ");
            sb.Append($"t{inv(d)} = 0;\n            }} else {{\n");
            sb.Append("                // (the bits each limb passes to the next)\n");
            sb.Append("                // Stryker disable once Bitwise: unsigned operands, >> and >>> are the same\n");
            sb.Append("                ulong " + string.Join(", ", Enumerable.Range(0, d).Select(k => $"c{inv(k)} = r{inv(k)} >> (64 - s)")) + ";\n");
            sb.Append("                t0 = r0 << s;\n");
            for (int k = 1; k < d; ++k)
                sb.Append($"                t{inv(k)} = (r{inv(k)} << s) | c{inv(k - 1)};\n");
            sb.Append($"                t{inv(d)} = c{inv(d - 1)};\n            }}\n");
            // the add with carry into a[0 .. d]
            sb.Append("            ulong x = a[0] + t0;\n");
            sb.Append("            carry = (x < t0) ? 1UL : 0UL;\n");
            sb.Append("            a[0] = x;\n");
            for (int k = 1; k <= d; ++k) {
                sb.Append($"            x = a[{inv(k)}] + t{inv(k)};\n");
                sb.Append($"            hi = (x < t{inv(k)}) ? 1UL : 0UL;\n");
                sb.Append("            x += carry;\n");
                if (k == d)
                    sb.Append("            // Stryker disable once Assignment: the two carries of a limb exclude each other, and the loop below tests this one against 0 only\n");
                sb.Append("            hi += (x < carry) ? 1UL : 0UL;\n");
                sb.Append($"            a[{inv(k)}] = x;\n");
                sb.Append("            carry = hi;\n");
            }
            sb.Append("            // (the accumulator's bound: the carry ends inside it; checked as above)\n");
            sb.Append($"            for (uint k = w + {inv(d + 1)}; carry != 0; ++k) {{\n");
            sb.Append("                if (k >= (uint)limbs)\n");
            sb.Append("                    throw new InvalidOperationException(\"DoublePredicates: a carry outside its accumulator\");\n");
            sb.Append("                ulong* c = (negative ? q : p) + k;\n");
            sb.Append("                *c += 1;\n");
            sb.Append("                carry = (*c == 0) ? 1UL : 0UL;\n");
            sb.Append("            }\n        }\n");
        }

        static void kernel(StringBuilder sb, MonomialPredicate p)
        {
            int n = p.Inputs.Count, d = p.Degree;
            string pars = string.Join(", ", p.Inputs.Select(i => "double " + i.Replace(".", "")));
            sb.Append("\n        /// <summary>\n");
            sb.Append($"        /// {p.Name}: the sign of {inv(p.Monomials.Count)} monomials of degree {inv(d)} in the coordinates.\n");
            sb.Append($"        /// A monomial is below 2^{inv(MantissaBits * d)} before its shift; with s = emax - emin the accumulators take\n");
            sb.Append($"        /// floor({inv(d)} s / 64) + {inv(p.ExtraLimbs)} limbs each ({inv(p.GuardBits)} guard bits): {inv(p.Limbs(0))} for inputs of one exponent, {inv(p.Limbs(MonomialPass.MaxSpan))} at the largest span of\n");
            sb.Append($"        /// two doubles (2045).\n");
            sb.Append("        /// </summary>\n");
            sb.Append("#if NET\n        [SkipLocalsInit]\n#endif\n");
            sb.Append("        [MethodImpl(JitHints.Optimize)]\n");
            sb.Append($"        public static int {p.Name}({pars})\n        {{\n");
            sb.Append($"            ulong* m = stackalloc ulong[{inv(n)}];\n");
            sb.Append($"            int* e = stackalloc int[{inv(n)}];\n");
            sb.Append("            ulong neg = 0;\n");
            sb.Append("            int emin = int.MaxValue, emax = int.MinValue;\n");
            for (int i = 0; i < n; ++i)
                sb.Append($"            load({p.Inputs[i].Replace(".", "")}, {inv(i)}, m, e, ref neg, ref emin, ref emax);\n");
            sb.Append("            // (every coordinate zero)\n");
            sb.Append("            if (emin == int.MaxValue)\n                return 0;\n");
            sb.Append("            // Stryker disable once Arithmetic: a larger span only gives more limbs than needed (the same sign)\n");
            sb.Append("            int span = emax - emin;\n");
            sb.Append($"            int limbs = {inv(d)} * span / 64 + {inv(p.ExtraLimbs)};\n");
            sb.Append("            ulong* p = stackalloc ulong[2 * limbs];\n");
            sb.Append("            ulong* q = p + limbs;\n");
            sb.Append("            for (int i = 0; i < 2 * limbs; ++i)\n                p[i] = 0;\n");
            sb.Append($"            int b = {inv(d)} * emin;\n");
            foreach (var mono in p.Monomials) {
                string text = string.Join(" ", mono.inputs.Select(i => p.Inputs[i]));
                sb.Append($"            add{inv(d)}(p, q, limbs, m, e, neg, b, {string.Join(", ", mono.inputs.Select(inv))}, {(mono.sign < 0 ? "true" : "false")});     // {(mono.sign < 0 ? "-" : "+")} {text}\n");
            }
            sb.Append("            return compare(p, q, limbs);\n        }\n");
        }
    }
