#!/usr/bin/env bash
# Runs one Stryker config in the mode select_shards.py chose (.github/workflows/mutation.yml, README.md):
#   full    the whole config, with its break threshold
#   source  incremental (incremental.py): Stryker mutates only the lines changed against the baseline report in
#           $BASELINE_DIR (default ./baseline, restored from the Actions cache); the score of the shard combines
#           these results with the baseline's for the unchanged code, and the break threshold applies to it.
#           Without a usable baseline the whole config runs, as in full (and StrykerOutput/full-run marks that)
#   tests   --since: the mutants covered by the changed tests, report only
# Stryker mutates and instruments EVERY source file of the library whatever `mutate` says (the filter only marks the other
# files' mutants as ignored, after the coverage capture): the capture then costs some 100 to 400 times the suite. So before
# Stryker runs, exclude_other_sources.py puts a "<auto-generated/>" comment line on top of every library file that the shard
# does not mutate (Stryker compiles but does not mutate such a file), and the line is taken off again when the script ends,
# also when Stryker fails or the job is cancelled, with a check that the tracked files are as they were (README, "Coverage
# pass"; from #615). G3_NO_EXCLUDE=1 switches this off (measurements).
# Pull requests (NO_FULL=1, set by the workflow for pull_request events; Exact Boolean 3.0, README "3.0 process"): no full
# run, because a full shard is a 3-6 hour runner slot. A shard that would run in full (its config or the tools changed, or
# no baseline in the cache fits) runs nothing, says "full run on master" and why in the job summary, and succeeds; the
# scheduled run on master measures it and seeds its baseline. Incremental (source) and --since (tests) runs are not
# affected. One exception, the gate of CLAUDE.md ("Review before every merge"): a shard that mutates an exact-code
# file that the PR changes (select_shards.py gate) keeps its full run, so such a PR is never merged without a threshold check.
# Usage (in tests/mutation): MODE=... BASE=<base sha> [NO_FULL=1] [BASELINE_DIR=<dir>] bash run_stryker.sh <config file>
set -euo pipefail
config="$1"
here="$(cd "$(dirname "$0")" && pwd)"
baseline="${BASELINE_DIR:-baseline}/stryker-report.json"
summary="${GITHUB_STEP_SUMMARY:-/dev/null}"
root="$(cd "$here/../.." && pwd)"

# the other files of the library are marked as not mutated while this script runs
if [ "${G3_NO_EXCLUDE:-}" != 1 ]; then
  tracked_clean=0
  if git -C "$root" diff --quiet 2>/dev/null; then tracked_clean=1; fi
  rc_restore=0
  restore_sources() {
    trap - EXIT
    # (no second signal may cut the restore short: GNU timeout and a cancelled job signal the whole process group, and an
    # ignored signal stays ignored in the undo process too; Stryker and its test hosts are stopped first, so that nothing
    # runs on against the restored files)
    trap '' INT TERM
    # (`|| true`: `set -e` must not end the restore when Stryker has exited already and the kill finds no process)
    if [ -n "${stryker_pid:-}" ] && declare -F kill_tree >/dev/null; then kill_tree "$stryker_pid" || true; fi
    python3 "$here/exclude_other_sources.py" undo --root "$root" >/dev/null || rc_restore=1
    if [ "$tracked_clean" = 1 ] && ! git -C "$root" diff --quiet 2>/dev/null; then
      echo "::error::the source files differ from the checkout after the mutation run: exclude_other_sources.py undo did not restore them" >&2
      git -C "$root" diff --stat | tail -5 >&2
      rc_restore=1
    fi
    return 0
  }
  # (the exit code of the script is kept unless the restore failed; bash runs the EXIT trap also when SIGTERM (a cancelled
  # job) or SIGINT ends it, test_run_stryker_restore.py; only SIGKILL skips it, and the CI checkout is thrown away then)
  # (the signals are ignored as the first step after $? is read: a second signal between the start of finish and the
  # restore's own `trap '' INT TERM` would otherwise end bash with the EXIT trap already cleared)
  finish() { local rc=$?; trap '' INT TERM; restore_sources; if [ "$rc_restore" = 1 ] && [ "$rc" = 0 ]; then rc=1; fi; exit "$rc"; }
  trap finish EXIT
  python3 "$here/exclude_other_sources.py" apply "$config" --root "$root" || exit 2
fi

# what the runner has (a standard runner of a public repository should have 4 vCPU and 16 GB: the basis of the
# concurrency and heap limit of the configs)
echo "runner: $(nproc 2>/dev/null || echo '?') cpus, $(free -m 2>/dev/null | awk '/^Mem:/ {print $2}' || true) MB memory"

# dotnet stryker with a progress line every 10 minutes in the job log: Stryker's progress reporter prints nothing
# without a terminal, so the line counts the test runs started, one log file each in StrykerOutput/*/logs (written with
# --log-to-file), against the mutants to test from Stryker's own log. A shard that will not finish within the job's
# limit shows it before it is cancelled.
# Early stop: once the coverage pass is over (Stryker's count of mutants to test is known), the rate of test runs since
# then projects the total run time (time so far + the mutants left at that rate). When the projection is above the limit
# times G3_STOP_FACTOR (1.15) at two ticks in a row, and at least G3_MIN_RUNS (30) runs were started since, the run is
# stopped and the script ends with 3: a shard that will be cancelled at the job's limit anyway frees its runner hours
# earlier, and the log says why. G3_LIMIT_SECONDS is the job's limit (21000 s = 350 min), G3_NO_EARLY_STOP=1 switches it off.
# kills a process and all its descendants (Stryker's test hosts would otherwise run on after the stop)
kill_tree() {
  local c
  for c in $(pgrep -P "$1" 2>/dev/null); do kill_tree "$c"; done
  kill -KILL "$1" 2>/dev/null
  return 0
}

stryker() {
  local started=$SECONDS
  rm -f StrykerOutput/stopped-early
  dotnet stryker --log-to-file "$@" &
  local pid=$!
  stryker_pid=$pid
  # (the subshell must not inherit `set -e` / pipefail: `ls` of a log directory that does not exist yet would end it, and
  # no progress line would ever appear when Stryker writes its logs late; it also means a real bug in the ticker
  # shows as a missing progress line, not as a failed job, which is acceptable for a progress line)
  ( set +e +o pipefail
    limit="${G3_LIMIT_SECONDS:-21000}"; base_t=""; base_r=""; strikes=0
    while sleep "${PROGRESS_SECONDS:-600}" </dev/null >/dev/null 2>&1; do
      logs="$(ls -d StrykerOutput/*/logs 2>/dev/null | sort | tail -1 || true)"
      [ -n "$logs" ] || continue
      total="$(grep -ho '[0-9]\+ *total mutants will be tested' "$logs"/log-*.txt 2>/dev/null | tail -1 | grep -o '^[0-9]\+' || true)"
      runs="$(ls "$logs" 2>/dev/null | grep -c '^Runner ' || true)"
      line="[progress $(date -u +%H:%M) UTC] test runs started: $runs, mutants to test: ${total:-not yet known}"
      if [ -n "$total" ]; then
        now=$SECONDS
        if [ -z "$base_t" ]; then
          base_t=$now; base_r=$runs
        else
          proj="$(awk -v n="$now" -v s="$started" -v t="$base_t" -v r="$runs" -v r0="$base_r" -v tot="$total" -v min="${G3_MIN_RUNS:-30}" \
                  'BEGIN { d = r - r0; if (d < min || n <= t) { exit } rem = tot - r; if (rem < 0) rem = 0; printf "%d", (n - s) + rem / (d / (n - t)) }')"
          if [ -n "$proj" ]; then
            line="$line, projected total: $((proj / 60)) min (limit $((limit / 60)) min)"
            if awk -v p="$proj" -v l="$limit" -v f="${G3_STOP_FACTOR:-1.15}" 'BEGIN { exit !(p > l * f) }'; then
              strikes=$((strikes + 1))
            else
              strikes=0
            fi
          fi
        fi
      fi
      echo "$line"
      if [ "$strikes" -ge 2 ] && [ "${G3_NO_EARLY_STOP:-0}" != 1 ]; then
        msg="stopped early: $runs of $total mutants started after $(((SECONDS - started) / 60)) min, the projection of the total ($((proj / 60)) min) is over the limit of $((limit / 60)) min"
        echo "::error::$msg"
        echo "$msg" > StrykerOutput/stopped-early
        echo "### Mutation run stopped early" >> "${GITHUB_STEP_SUMMARY:-/dev/null}"; echo "$msg" >> "${GITHUB_STEP_SUMMARY:-/dev/null}"
        kill_tree "$pid"
        break
      fi
    done ) &
  local ticker=$!
  local rc=0
  wait "$pid" || rc=$?
  # (reaped: the restore must not kill a process that reuses the id)
  stryker_pid=
  if [ -f StrykerOutput/stopped-early ]; then
    wait "$ticker" 2>/dev/null
    return 3
  fi
  kill "$ticker" 2>/dev/null || true
  return $rc
}

# the config of a full run: narrowed to the tests that kill the shard's mutants if a current filter file
# ($G3_TEST_FILTERS/<config name>, default tests/mutation/test-filters; narrow_tests.py, README "Narrowed test sets")
# exists; else, or with G3_FULL_TESTS=1 or in the scheduled run of a Sunday, the config itself (a stale filter says so and also falls back to it)
full_config() {
  local flt="${G3_TEST_FILTERS:-$here/test-filters}/$(basename "$config")"
  # the check of record: G3_FULL_TESTS=1, and every scheduled run on a Sunday (UTC; G3_WEEKDAY overrides `date -u +%u`, 7 = Sunday)
  # runs the whole filter, so a kill that the narrowed runs lost shows up within a week
  local unfiltered="${G3_FULL_TESTS:-0}"
  if [ "${GITHUB_EVENT_NAME:-}" = schedule ] && [ "${G3_WEEKDAY:-$(date -u +%u)}" = 7 ]; then unfiltered=1; fi
  if [ "$unfiltered" != 1 ] && [ -f "$flt" ]; then
    local msg
    msg="$(python3 "$here/narrow_tests.py" apply --config "$config" --filter "$flt" --repo "$(cd "$here/../.." && pwd)" -o narrowed-run.json)"
    echo "test set: $msg" >&2
    echo "test set: $msg" >> "$summary"
    echo narrowed-run.json
  else
    echo "$config"
  fi
}

# a full run that a pull request does not make: the reason goes to the log and the job summary, the job succeeds
skip_full() {
  mkdir -p StrykerOutput
  echo "::notice::$config: full run on master ($1)"
  {
    echo "### $config: full run on master"
    echo
    echo "No full run on a pull request during 3.0: $1. The scheduled run on master measures this shard in full and seeds its baseline (tests/mutation/README.md)."
  } >> "$summary"
  touch StrykerOutput/skipped-full
}

# does the PR change an exact-code file that this shard mutates, or a script of the runs while this is their
# representative shard (then its full run stays)? Fails closed: the full run is skipped only when select_shards.py answers
# exactly `no`; a git or script error counts as gated. G3_CHANGED_PATHS_FILE (a list of paths) replaces the git diff, for the tests
gated() {
  local changed answer
  if [ -n "${G3_CHANGED_PATHS_FILE:-}" ]; then
    changed="$(cat "$G3_CHANGED_PATHS_FILE")" || return 0
  else
    changed="$(git -C "$root" diff --name-only "${BASE:-HEAD}...HEAD" 2>/dev/null)" || return 0
  fi
  answer="$(python3 "$here/select_shards.py" gate "$config" <<< "$changed" 2>/dev/null)" || return 0
  [ "$answer" != no ]
}

# usage: full <why a full run is needed>
full() {
  if [ "${NO_FULL:-}" = 1 ]; then
    if gated; then
      echo "::notice::$config: full run on this PR although NO_FULL is set: the PR changes an exact-code file of this shard (gate)"
    else
      skip_full "${1:-a full run is needed}"
      return 0
    fi
  fi
  mkdir -p StrykerOutput
  touch StrykerOutput/full-run
  local run
  run="$(full_config)"
  echo "dotnet stryker --config-file $run"
  stryker --config-file "$run"
}

latest_report() {
  ls StrykerOutput/*/reports/mutation-report.json 2>/dev/null | sort | tail -1
}

case "${MODE:-full}" in
  tests)
    echo "dotnet stryker --config-file $config --since:$BASE --break-at 0"
    stryker --config-file "$config" "--since:$BASE" --break-at 0 ;;
  source)
    if [ ! -f "$baseline" ]; then
      echo "::notice::no baseline in the cache for $config: running it in full"
      full "no baseline in the cache fits this config"
      exit $?
    fi
    echo "baseline: $(cat "$(dirname "$baseline")/source.txt" 2>/dev/null || echo unknown)"
    out="$(python3 "$here/incremental.py" plan "$config" "$baseline" incremental-run.json)"
    echo "$out"
    plan="$(sed -n 's/^plan=//p' <<< "$out" | tail -1)"
    case "$plan" in
      run)
        echo "dotnet stryker --config-file incremental-run.json --break-at 0"
        stryker --config-file incremental-run.json --break-at 0
        report="$(latest_report)"
        if [ -z "$report" ]; then
          echo "::error::the incremental run wrote no report"
          exit 1
        fi
        python3 "$here/incremental.py" merge "$config" "$baseline" "$report" "$summary" ;;
      none)
        python3 "$here/incremental.py" merge "$config" "$baseline" - "$summary" ;;
      *)
        full "the baseline does not fit the changed lines (plan: $plan)" ;;
    esac ;;
  full)
    full "the config or the tools changed" ;;
  *)
    echo "unknown mode $MODE" >&2
    exit 2 ;;
esac
