#!/usr/bin/env python3
"""Tests of exclude_other_sources.py. Run by the changes job of the mutation workflow."""
import json
import os
import shutil
import tempfile
import unittest

import exclude_other_sources as ex


def config(*mutate):
    return json.dumps({"stryker-config": {"mutate": list(mutate)}})


class Exclude(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp()
        self.files = {
            "mesh_ops/ExactMeshBoolean.cs": b"// header\r\nusing System;\r\nclass A {}\r\n",
            "mesh_ops/Other.cs": b"\xef\xbb\xbfusing System;\nclass B {}\n",
            "math/ExactPredicates.cs": b"class C {}",
            "math/Sub/Deep.cs": b"// x\nclass D {}\n",
            "tests/geometry3Sharp.Tests/T.cs": b"class T {}\n",
            "tools/x/Y.cs": b"class Y {}\n",
            "docs/examples/Z.cs": b"class Z {}\n",
            "benchmarks/B/B.cs": b"class BB {}\n",
            "mesh_ops/obj/Gen.cs": b"class G {}\n",
            "mesh_ops/readme.txt": b"text\n",
        }
        for rel, data in self.files.items():
            p = os.path.join(self.root, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "wb") as f:
                f.write(data)
        self.cfg = os.path.join(self.root, "stryker.json")
        with open(self.cfg, "w") as f:
            f.write(config("**/mesh_ops/ExactMeshBoolean.cs{0..100}"))

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def read(self, rel):
        with open(os.path.join(self.root, rel), "rb") as f:
            return f.read()

    def snapshot(self):
        return {rel: self.read(rel) for rel in self.files}

    def test_the_other_library_files_get_the_marker_and_the_shard_file_does_not(self):
        n, kept = ex.apply(self.cfg, self.root)
        self.assertEqual((3, 1), (n, kept))
        marker = ex.MARKER.encode()
        self.assertEqual(self.files["mesh_ops/ExactMeshBoolean.cs"], self.read("mesh_ops/ExactMeshBoolean.cs"))
        self.assertEqual(marker + b"\n" + b"class C {}", self.read("math/ExactPredicates.cs"))        # (no line break at the end: kept)
        self.assertEqual(b"\xef\xbb\xbf" + marker + b"\n" + b"using System;\nclass B {}\n", self.read("mesh_ops/Other.cs"))   # (after the BOM)
        self.assertEqual(marker + b"\n" + self.files["math/Sub/Deep.cs"], self.read("math/Sub/Deep.cs"))
        for rel in ("tests/geometry3Sharp.Tests/T.cs", "tools/x/Y.cs", "docs/examples/Z.cs", "benchmarks/B/B.cs", "mesh_ops/obj/Gen.cs", "mesh_ops/readme.txt"):
            self.assertEqual(self.files[rel], self.read(rel), rel)

    def test_the_marker_makes_stryker_see_an_auto_generated_file(self):
        # (Stryker's GeneratedCodeFilterExtension: the leading trivia has a comment that contains "<auto-generated")
        self.assertIn("<auto-generated", ex.MARKER)
        self.assertTrue(ex.MARKER.startswith("//"))
        ex.apply(self.cfg, self.root)
        self.assertTrue(self.read("math/ExactPredicates.cs").startswith(ex.MARKER.encode()))

    def test_crlf_files_get_a_crlf_marker_line(self):
        with open(os.path.join(self.root, "mesh_ops/Other.cs"), "wb") as f:
            f.write(b"using System;\r\nclass B {}\r\n")
        ex.apply(self.cfg, self.root)
        self.assertTrue(self.read("mesh_ops/Other.cs").startswith(ex.MARKER.encode() + b"\r\nusing"))

    def test_apply_is_idempotent_and_undo_restores_every_byte(self):
        before = self.snapshot()
        ex.apply(self.cfg, self.root)
        once = self.snapshot()
        self.assertEqual((0, 1), ex.apply(self.cfg, self.root))
        self.assertEqual(once, self.snapshot())
        self.assertEqual(3, ex.undo(self.root))
        self.assertEqual(before, self.snapshot())
        self.assertEqual(0, ex.undo(self.root))

    def test_a_mutate_entry_that_matches_nothing_is_an_error_and_changes_nothing(self):
        with open(self.cfg, "w") as f:
            f.write(config("**/mesh_ops/ExactMeshBoolean.cs", "**/mesh_ops/Missing.cs"))
        before = self.snapshot()
        with self.assertRaises(ValueError):
            ex.apply(self.cfg, self.root)
        self.assertEqual(before, self.snapshot())

    def test_several_files_and_the_plain_glob_are_kept(self):
        with open(self.cfg, "w") as f:
            f.write(config("**/mesh_ops/ExactMeshBoolean.cs", "**/math/ExactPredicates.cs", "**/Sub/*.cs"))
        n, kept = ex.apply(self.cfg, self.root)
        self.assertEqual((1, 3), (n, kept))
        self.assertEqual(self.files["math/ExactPredicates.cs"], self.read("math/ExactPredicates.cs"))
        self.assertEqual(self.files["math/Sub/Deep.cs"], self.read("math/Sub/Deep.cs"))

    def test_glob_matching(self):
        rx = ex.glob_regex("**/mesh_ops/ExactMeshBoolean.cs")
        self.assertTrue(rx.match("mesh_ops/ExactMeshBoolean.cs"))
        self.assertTrue(rx.match("a/b/mesh_ops/ExactMeshBoolean.cs"))
        self.assertFalse(rx.match("mesh_ops/ExactMeshBoolean.cs.bak"))
        self.assertFalse(rx.match("xmesh_ops/ExactMeshBoolean.cs"))
        self.assertTrue(ex.glob_regex("**/mesh_ops/TerrainSlope*.cs").match("mesh_ops/TerrainSlopeMap.cs"))
        self.assertFalse(ex.glob_regex("**/mesh_ops/TerrainSlope*.cs").match("mesh_ops/sub/TerrainSlopeMap.cs"))

    def test_every_real_config_names_files_that_exist(self):
        # (a shard whose mutate entry matched nothing would mark every file as not mutated)
        here = os.path.dirname(os.path.abspath(__file__))
        repo = os.path.abspath(os.path.join(here, "..", ".."))
        files = ex.library_files(repo)
        self.assertGreater(len(files), 200)
        import glob
        configs = glob.glob(os.path.join(here, "stryker*.json"))
        self.assertGreater(len(configs), 20)
        for c in configs:
            self.assertTrue(ex.shard_files(c, files), c)


if __name__ == "__main__":
    unittest.main()
