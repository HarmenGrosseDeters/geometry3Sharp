#!/usr/bin/env python3
"""Keeps Stryker from mutating (and instrumenting) the files that a shard does not test.

Stryker.NET 5.0 and 5.1 mutate EVERY source file of the project, compile all the mutants into the assembly, and capture
coverage with all of them in place; the `mutate` patterns only mark the mutants of other files as ignored afterwards
(StrykerRunner.cs: Mutate, AnalyzeCoverage, then FilterMutants; CsharpMutationProcess.cs; FilePatternMutantFilter.cs), so a
shard with a few hundred mutants still pays the coverage recording (a lock around a set on every execution of every
mutant site, InjectedHelpers/MutantControl.cs IsActive / RegisterCoverage) for the 138 000 mutants of the library. A source
file that starts with an auto-generated comment is not mutated (CsharpProjectComponentsBuilder.cs, GeneratedCodeFilterExtension:
the leading trivia contains `<auto-generated`), only compiled. This script puts one such comment line at the top of every
library source file that the shard's `mutate` patterns do not name, so the code under test is the same (a comment is the only
change) and only the shard's files carry mutants.

  python3 exclude_other_sources.py apply <stryker config> [--root R]   # add the line to the other files
  python3 exclude_other_sources.py undo [--root R]                     # remove it again (idempotent)

Use it on a throw-away checkout (the workflow) or between `git status` checks (run_local.sh restores the files itself). The
files of the shard are not touched, so the offsets of `mutate` spans and the baselines stay as they are. Files of the
projects that are not part of the library (tests, benchmarks, tools, docs, addons) are left alone.
"""
import json
import os
import re
import sys

import incremental

MARKER = "// <auto-generated/> not mutated by this mutation shard (tests/mutation/exclude_other_sources.py)"
SKIP_DIRS = {"tests", "benchmarks", "tools", "docs", "addons", "obj", "bin", "StrykerOutput", ".git", "Properties", "node_modules"}
BOM = b"\xef\xbb\xbf"


def glob_regex(glob):
    """regex for a mutate glob (`**/dir/File.cs`): `**/` any directories, `*` within a name"""
    out, i = "", 0
    glob = glob.replace("\\", "/")
    while i < len(glob):
        if glob.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif glob[i] == "*":
            out += "[^/]*"
            i += 1
        elif glob[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(glob[i])
            i += 1
    return re.compile("^" + out + "$")


def library_files(root):
    """repository-relative paths ('/') of the .cs files of the library project"""
    found = []
    for d, dirs, files in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        rel_dir = os.path.relpath(d, root).replace(os.sep, "/")
        for f in sorted(files):
            if f.endswith(".cs"):
                found.append(f if rel_dir == "." else rel_dir + "/" + f)
    return found


def shard_files(config_path, files):
    """the files that the `mutate` entries of the config name (all of them must name one)"""
    with open(config_path, encoding="utf-8-sig") as fh:
        cfg = json.load(fh)["stryker-config"]
    named = set()
    for entry in cfg["mutate"]:
        glob, _ = incremental.parse_mutate(entry)
        rx = glob_regex("**/" + glob)             # (parse_mutate drops the leading **/: a pattern names a file anywhere below the root)
        hits = [f for f in files if rx.match(f)]
        if not hits:
            raise ValueError("the mutate entry %r matches no source file of the library" % entry)
        named.update(hits)
    return named


def split_first_line(data):
    """(bom, first line without its line break, line break, rest)"""
    bom = BOM if data.startswith(BOM) else b""
    body = data[len(bom):]
    m = re.search(rb"\r?\n", body)
    if not m:
        return bom, body, b"", b""
    return bom, body[:m.start()], m.group(0), body[m.end():]


def eol_of(data):
    return b"\r\n" if b"\r\n" in data else b"\n"


def apply(config_path, root):
    files = library_files(root)
    keep = shard_files(config_path, files)
    changed = 0
    for rel in files:
        if rel in keep:
            continue
        path = os.path.join(root, rel)
        with open(path, "rb") as fh:
            data = fh.read()
        bom, first, _, _ = split_first_line(data)
        if first.decode("utf-8", "replace") == MARKER:
            continue
        body = data[len(bom):]
        with open(path, "wb") as fh:
            fh.write(bom + MARKER.encode("utf-8") + eol_of(data) + body)
        changed += 1
    return changed, len(keep)


def undo(root):
    changed = 0
    for rel in library_files(root):
        path = os.path.join(root, rel)
        with open(path, "rb") as fh:
            data = fh.read()
        bom, first, brk, rest = split_first_line(data)
        if first.decode("utf-8", "replace") != MARKER:
            continue
        with open(path, "wb") as fh:
            fh.write(bom + rest)
        changed += 1
    return changed


def main(argv):
    root = "."
    if "--root" in argv:
        i = argv.index("--root")
        root = argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    if len(argv) == 2 and argv[0] == "apply":
        try:
            n, kept = apply(argv[1], root)
        except (ValueError, OSError) as e:
            print("error: %s" % e, file=sys.stderr)
            return 2
        print("marked %d source files as not mutated, %d stay mutable" % (n, kept))
        return 0
    if len(argv) == 1 and argv[0] == "undo":
        print("restored %d source files" % undo(root))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
