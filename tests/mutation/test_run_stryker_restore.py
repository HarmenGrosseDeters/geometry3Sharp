#!/usr/bin/env python3
"""run_stryker.sh marks the library files a shard does not mutate (exclude_other_sources.py) only while Stryker runs: after a
run that succeeds, fails, or is cancelled (SIGTERM, as GitHub cancels a job; SIGINT), no tracked file differs from the
checkout, and a run whose restore cannot bring the files back fails. A copy of the scripts in a throw-away git repository,
with a stub `dotnet` that records what it saw."""
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import unittest
import shell_shims

HERE = os.path.dirname(os.path.abspath(__file__))
MARKER = "// <auto-generated/> not mutated by this mutation shard (tests/mutation/exclude_other_sources.py)"
SCRIPTS = ("run_stryker.sh", "exclude_other_sources.py", "incremental.py", "narrow_tests.py")
CONFIG = '{"stryker-config": {"project": "x.csproj", "mutate": ["**/mesh_ops/Shard.cs{0..1000000}"], "test-case-filter": "X"}}'
# the stub: on `dotnet stryker ...` it writes the first line of the other file (marked or not) and of the shard's file to
# $SEEN, then exits, fails, hangs or changes a file as $STUB says
STUB = r'''#!/usr/bin/env bash
if [ "$1" = stryker ]; then
  root="$(cd ../.. && pwd)"
  head -c 200 "$root/math/Other.cs" | head -1 > "$SEEN.other"
  head -c 200 "$root/mesh_ops/Shard.cs" | head -1 > "$SEEN.shard"
  case "$STUB" in
    fail) exit 1 ;;
    hang) echo $$ > "$SEEN.pid"; touch "$SEEN.started"; exec sleep 60 ;;
    damage) printf 'x' >> "$root/math/Other.cs"; exit 0 ;;
  esac
  mkdir -p StrykerOutput/run/reports
  echo '{}' > StrykerOutput/run/reports/mutation-report.json
fi
exit 0
'''


def alive(pid):
    """the process exists and is not a zombie"""
    try:
        with open("/proc/%d/stat" % pid) as f:
            return f.read().rsplit(")", 1)[1].split()[0] != "Z"
    except OSError:
        return False


class RunStrykerRestore(unittest.TestCase):

    def setUp(self, extra_files=0):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = os.path.join(self.tmp.name, "repo")
        mut = os.path.join(self.root, "tests", "mutation")
        os.makedirs(mut)
        for s in SCRIPTS:
            shutil.copy(os.path.join(HERE, s), mut)
        with open(os.path.join(mut, "stryker-x.json"), "w", encoding="utf-8", newline="\n") as f:
            f.write(CONFIG)
        os.makedirs(os.path.join(self.root, "math"))
        os.makedirs(os.path.join(self.root, "mesh_ops"))
        # (a BOM and CRLF file, and an LF file: the restore must give back every byte)
        with open(os.path.join(self.root, "math", "Other.cs"), "wb") as f:
            f.write(b"\xef\xbb\xbfnamespace g3\r\n{\r\n}\r\n")
        with open(os.path.join(self.root, "mesh_ops", "Shard.cs"), "wb") as f:
            f.write(b"namespace g3\n{\n}\n")
        for i in range(extra_files):
            with open(os.path.join(self.root, "math", "More%d.cs" % i), "w", encoding="utf-8", newline="\n") as f:
                f.write("namespace g3 { class More%d { } }\n" % i)
        with open(os.path.join(self.root, ".gitignore"), "w", encoding="utf-8", newline="\n") as f:
            f.write("StrykerOutput/\n__pycache__/\n")
        git = ["git", "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(git + ["init", "-q"], cwd=self.root, check=True)
        subprocess.run(git + ["add", "-A"], cwd=self.root, check=True)
        subprocess.run(git + ["commit", "-qm", "init"], cwd=self.root, check=True)
        self.bin = os.path.join(self.tmp.name, "bin")
        os.makedirs(self.bin)
        shell_shims.add_python3(self.bin)
        with open(os.path.join(self.bin, "dotnet"), "w", encoding="utf-8", newline="\n") as f:
            f.write(STUB)
        os.chmod(os.path.join(self.bin, "dotnet"), 0o755)
        self.seen = os.path.join(self.tmp.name, "seen")

    def tearDown(self):
        self.tmp.cleanup()

    def env(self, stub):
        e = dict(os.environ, PATH=self.bin + os.pathsep + os.environ["PATH"], MODE="full", STUB=stub, SEEN=self.seen,
                 GITHUB_STEP_SUMMARY=os.path.join(self.tmp.name, "summary"), PROGRESS_SECONDS="1000000")
        for k in ("G3_NO_EXCLUDE", "GITHUB_OUTPUT", "NO_FULL"):
            e.pop(k, None)
        return e

    def start(self, stub, session=False):
        # (output to a file: after a signal the stub's sleep may still hold a pipe open)
        self.log = open(os.path.join(self.tmp.name, "log-" + stub), "w+")
        return subprocess.Popen(["bash", "run_stryker.sh", "stryker-x.json"], cwd=os.path.join(self.root, "tests", "mutation"),
                                env=self.env(stub), stdout=self.log, stderr=subprocess.STDOUT, text=True,
                                start_new_session=session)

    def finish(self, p, timeout=60):
        p.wait(timeout=timeout)
        self.log.seek(0)
        out = self.log.read()
        self.log.close()
        return out

    def status(self):
        return subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=self.root, capture_output=True,
                              text=True, check=True).stdout

    def seen_lines(self):
        with open(self.seen + ".other", encoding="utf-8-sig") as f:
            other = f.read().strip()
        with open(self.seen + ".shard", encoding="utf-8") as f:
            shard = f.read().strip()
        return other, shard

    def test_marked_while_stryker_runs_and_restored_after_success_and_failure(self):
        for stub, rc in (("ok", 0), ("fail", 1)):
            p = self.start(stub)
            out = self.finish(p)
            self.assertEqual(rc, p.returncode, out)
            other, shard = self.seen_lines()
            self.assertEqual(MARKER, other, stub)            # the other file was marked while Stryker ran
            self.assertEqual("namespace g3", shard, stub)    # the shard's file was not
            self.assertEqual("", self.status(), stub + "\n" + out)

    @unittest.skipIf(os.name == "nt", "POSIX signals: Windows has no os.killpg and send_signal terminates bash outright, so the trap of run_stryker.sh cannot run; CI runs it on Linux")
    def test_a_cancelled_run_restores_the_sources(self):
        for sig in (signal.SIGTERM, signal.SIGINT):
            p = self.start("hang")
            t0 = time.time()
            while not os.path.exists(self.seen + ".started") and time.time() - t0 < 30:
                time.sleep(0.1)
            self.assertTrue(os.path.exists(self.seen + ".started"))
            self.assertNotEqual("", self.status())           # marked now
            p.send_signal(sig)
            out = self.finish(p, 30)
            self.assertNotEqual(0, p.returncode)
            self.assertEqual("", self.status(), "%s\n%s" % (sig, out))
            # (the signal went to the script alone: it stops Stryker itself, which would run on against the restored files)
            with open(self.seen + ".pid") as f:
                pid = int(f.read())
            for _ in range(50):
                if not alive(pid):
                    break
                time.sleep(0.1)
            self.assertFalse(alive(pid), "the stub Stryker runs on after %s" % sig)
            os.remove(self.seen + ".started")

    @unittest.skipIf(os.name == "nt", "POSIX signals: Windows has no os.killpg and send_signal terminates bash outright, so the trap of run_stryker.sh cannot run; CI runs it on Linux")
    def test_signals_to_the_whole_group_during_the_restore_do_not_cut_it_short(self):
        # GNU timeout and a cancelled job signal the process group, also again while the restore runs: with 1500 marked files
        # (the restore takes a while), SIGTERM to the group 30 times in a row, then nothing may stay marked, and the stub
        # Stryker (its sleep) is stopped rather than left running
        self.tearDown()
        self.setUp(extra_files=1500)
        p = self.start("hang", session=True)
        t0 = time.time()
        while not os.path.exists(self.seen + ".started") and time.time() - t0 < 60:
            time.sleep(0.1)
        self.assertTrue(os.path.exists(self.seen + ".started"))
        for _ in range(30):
            try:
                os.killpg(p.pid, signal.SIGTERM)
            except ProcessLookupError:
                break
            time.sleep(0.02)
        out = self.finish(p, 60)
        self.assertEqual("", self.status(), out)
        with open(self.seen + ".pid") as f:
            pid = int(f.read())
        self.assertFalse(alive(pid), "the stub Stryker runs on after the script ended")

    def test_a_restore_that_leaves_a_difference_fails_the_run(self):
        p = self.start("damage")
        out = self.finish(p)
        self.assertNotEqual(0, p.returncode, out)
        self.assertIn("differ from the checkout", out)

    def test_check_finds_a_left_over_marker(self):
        ex = os.path.join(self.root, "tests", "mutation", "exclude_other_sources.py")
        ok = subprocess.run([sys.executable, ex, "check", "--root", self.root], capture_output=True, text=True)
        self.assertEqual(0, ok.returncode, ok.stdout + ok.stderr)
        subprocess.run([sys.executable, ex, "apply", os.path.join(self.root, "tests", "mutation", "stryker-x.json"), "--root", self.root],
                       check=True, capture_output=True)
        bad = subprocess.run([sys.executable, ex, "check", "--root", self.root], capture_output=True, text=True)
        self.assertEqual(1, bad.returncode)
        self.assertIn("math/Other.cs", bad.stdout + bad.stderr)


if __name__ == "__main__":
    unittest.main()
