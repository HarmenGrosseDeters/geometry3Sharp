        // ---- the kernels against the BigInteger determinants ----

        static int Kernel(int kind, double[] v)
        {
            switch (kind) {
                case 2: return DoublePredicates.Orient2d(v[0], v[1], v[2], v[3], v[4], v[5]);
                case 3: return DoublePredicates.Orient3d(v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8], v[9], v[10], v[11]);
                default: return DoublePredicates.InCircle(v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7]);
            }
        }

        static int Reference(int kind, double[] v)
        {
            switch (kind) {
                case 2: return ExactPredicates.orient2d_bigint(new Vector2d(v[0], v[1]), new Vector2d(v[2], v[3]), new Vector2d(v[4], v[5]));
                case 3: return ExactPredicates.orient3d_bigint(new Vector3d(v[0], v[1], v[2]), new Vector3d(v[3], v[4], v[5]), new Vector3d(v[6], v[7], v[8]), new Vector3d(v[9], v[10], v[11]));
                default: return ExactPredicates.incircle_bigint(new Vector2d(v[0], v[1]), new Vector2d(v[2], v[3]), new Vector2d(v[4], v[5]), new Vector2d(v[6], v[7]));
            }
        }

        static readonly int[] Arity = { 0, 0, 6, 12, 8 };

        static double Bits(long b) { return BitConverter.Int64BitsToDouble(b); }

        // m 2^e (exact unless the result is subnormal; Math.ScaleB is not in .NET Framework)
        static double Scale(double m, int e)
        {
            while (e > 1000) { m *= Bits((long)(1000 + 1023) << 52); e -= 1000; }
            while (e < -1000) { m *= Bits((long)(-1000 + 1023) << 52); e += 1000; }
            return m * Bits((long)(e + 1023) << 52);
        }

        // the largest and smallest magnitudes of each kind: every mantissa bit set at both ends of the exponent range
        // (the accumulators carry through their whole length), the subnormals, powers of two, zero
        static readonly double[] Extremes = {
            double.MaxValue, -double.MaxValue, Bits(0x001FFFFFFFFFFFFFL), -Bits(0x001FFFFFFFFFFFFFL), Bits(0x000FFFFFFFFFFFFFL),
            -Bits(0x000FFFFFFFFFFFFFL), double.Epsilon, -double.Epsilon, 0.0, -0.0, 1.0, -1.0, Bits(0x3FFFFFFFFFFFFFFFL),
            Bits(0x7FE0000000000000L), Bits(0x0010000000000000L), Bits(0x0008000000000000L) };

        static double[] Case(string cls, int kind, Random rnd)
        {
            int n = Arity[kind];
            double[] v = new double[n];
            int dim = kind == 3 ? 3 : 2;
            switch (cls) {
                case "any exponent":
                    // small or random mantissas at any exponent, subnormals included; some repeated coordinates
                    for (int k = 0; k < n; ++k) {
                        double m = (rnd.Next(2) == 0) ? rnd.Next(-3, 4) : (rnd.NextDouble() + 1) * (rnd.Next(2) * 2 - 1);
                        v[k] = Scale(m, rnd.Next(-1074, 1020));
                        if (rnd.Next(8) == 0 && k >= dim) v[k] = v[k - dim];
                    }
                    break;
                case "three scales":
                    // the pattern of issue #711: corners near 2^-943 next to coordinates near 2^-106
                    int[] scales = { -943, -106, -100 };
                    for (int k = 0; k < n; ++k) {
                        double m = (rnd.Next(2) == 0) ? rnd.Next(-3, 4) : (rnd.NextDouble() + 1) * (rnd.Next(2) * 2 - 1);
                        v[k] = Scale(m, scales[rnd.Next(3)]);
                    }
                    break;
                case "extremes":
                    for (int k = 0; k < n; ++k) v[k] = Extremes[rnd.Next(Extremes.Length)];
                    break;
                case "degenerate, scaled":
                    // exactly degenerate (points of a lattice line, plane or circle) or one ulp off, at a scale outside the
                    // range of the expansions
                    double s = Scale(1.0, rnd.Next(2) == 0 ? rnd.Next(-1000, -200) : rnd.Next(200, 900));
                    if (kind == 4) {
                        // lattice points of the circle x^2 + y^2 = 32045 = 5 * 13 * 17 * 29, shifted
                        int ox = rnd.Next(-500, 500), oy = rnd.Next(-500, 500);
                        for (int q = 0; q < 4; ++q) { var c = Circle[rnd.Next(Circle.Count)]; v[2 * q] = (ox + c.Item1) * s; v[2 * q + 1] = (oy + c.Item2) * s; }
                    } else {
                        int[] o = { rnd.Next(-1000, 1000), rnd.Next(-1000, 1000), rnd.Next(-1000, 1000) };
                        int[] d1 = { rnd.Next(-9, 10), rnd.Next(-9, 10), rnd.Next(-9, 10) }, d2 = { rnd.Next(-9, 10), rnd.Next(-9, 10), rnd.Next(-9, 10) };
                        for (int q = 0; q < n / dim; ++q) {
                            int a = rnd.Next(-50, 51), b = (kind == 3) ? rnd.Next(-50, 51) : 0;
                            for (int j = 0; j < dim; ++j) v[q * dim + j] = (o[j] + a * d1[j] + b * d2[j]) * s;
                        }
                    }
                    if (rnd.Next(3) == 0) { int k = rnd.Next(n); v[k] = Bits(BitConverter.DoubleToInt64Bits(v[k]) + 1); }
                    break;
                default:
                    // in the range of the expansions (the kernels are not used there, but must be right everywhere)
                    for (int k = 0; k < n; ++k) v[k] = (rnd.Next(4) == 0) ? rnd.Next(-5, 6) : (rnd.NextDouble() - 0.5) * 200;
                    break;
            }
            return v;
        }

        static readonly List<Tuple<int, int>> Circle = LatticeCircle();
        static List<Tuple<int, int>> LatticeCircle()
        {
            var l = new List<Tuple<int, int>>();
            for (int x = -180; x <= 180; ++x)
                for (int y = -180; y <= 180; ++y)
                    if (x * x + y * y == 32045) l.Add(Tuple.Create(x, y));
            return l;
        }

        [Theory]
        [InlineData("any exponent", 4000)]
        [InlineData("three scales", 4000)]
        [InlineData("extremes", 6000)]
        [InlineData("degenerate, scaled", 4000)]
        [InlineData("in range", 4000)]
        public void Kernels_MatchTheBigIntegerDeterminants(string cls, int count)
        {
            for (int kind = 2; kind <= 4; ++kind) {
                var rnd = new Random(1000 * kind + cls.Length);
                int zeros = 0, positive = 0, negative = 0;
                for (int i = 0; i < count; ++i) {
                    double[] v = Case(cls, kind, rnd);
                    int expected = Reference(kind, v), got = Kernel(kind, v);
                    Assert.True(expected == got, $"{cls}, kind {kind}: {string.Join(" ", v.Select(x => x.ToString("R")))}: {got} instead of {expected}");
                    if (expected == 0) zeros++; else if (expected > 0) positive++; else negative++;
                }
                // the class reaches both signs, and the degenerate ones the zero
                Assert.True(positive > count / 50 && negative > count / 50, $"{cls}, kind {kind}: {positive} / {negative}");
                if (cls == "degenerate, scaled") Assert.True(zeros > count / 50, $"{cls}, kind {kind}: {zeros} zeros");
                if (cls == "extremes") Assert.True(zeros > 0, $"{cls}, kind {kind}: no zero");
            }
        }

        // the full carries: every mantissa bit set, at one exponent and at the two ends of the exponent range, in every
        // sign pattern of a small case
        [Fact]
        public void Kernels_FullMantissasAtTheEndsOfTheExponentRange()
        {
            double big = double.MaxValue, small = Bits(0x001FFFFFFFFFFFFFL), sub = Bits(0x000FFFFFFFFFFFFFL);
            foreach (double[] pair in new[] { new[] { big, big }, new[] { small, small }, new[] { big, small }, new[] { big, sub }, new[] { sub, sub }, new[] { big, double.Epsilon } })
                for (int kind = 2; kind <= 4; ++kind) {
                    int n = Arity[kind];
                    var rnd = new Random(kind);
                    for (int trial = 0; trial < 400; ++trial) {
                        double[] v = new double[n];
