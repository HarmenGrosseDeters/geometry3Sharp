        // Invariance over the similarities of the harness: on every transformed input the kernel is the BigInteger
        // determinant of the transformed doubles; under the exact ones (scales by a power of two) the sign is the
        // original's, case by case.
        [Fact]
        public void Kernels_Invariance()
        {
            var rnd = new Random(31);
            var cases = new List<double[]>();
            for (int i = 0; i < 300; ++i) cases.Add(Case(i % 3 == 0 ? "in range" : i % 3 == 1 ? "degenerate, scaled" : "three scales", 3, rnd));
            foreach (Similarity s in Similarity.All()) {
                foreach (double[] v in cases) {
                    double[] t = new double[12];
                    for (int q = 0; q < 4; ++q) {
                        Vector3d p = s.Apply(new Vector3d(v[3 * q], v[3 * q + 1], v[3 * q + 2]));
                        t[3 * q] = p.x; t[3 * q + 1] = p.y; t[3 * q + 2] = p.z;
                    }
                    if (t.Any(x => double.IsInfinity(x) || double.IsNaN(x))) continue;
                    int sign = Kernel(3, t);
                    Assert.True(Reference(3, t) == sign, $"{s}: the kernel differs from the BigInteger determinant");
                    // (a scale by 2^k is exact unless a coordinate leaves the normal range)
                    bool scaledExactly = true;
                    for (int k = 0; k < 12; ++k) scaledExactly &= t[k] / s.Scale == v[k] && (t[k] == 0 || Math.Abs(t[k]) >= Bits(0x0010000000000000L));
                    if (s.IsExact && scaledExactly)
                        Assert.True(Kernel(3, v) == sign, $"{s}: the sign changed under an exact scaling");
                }
            }
        }
    }
