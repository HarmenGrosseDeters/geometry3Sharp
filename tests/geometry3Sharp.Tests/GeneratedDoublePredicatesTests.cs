        // the derivation, with exact integers: the predicates have the documented shape, and for every exponent span the
        // two accumulators hold the sum of all monomials and every limb a monomial is written to
        [Fact]
        public void LimbRule_HoldsForEveryExponentSpan()
        {
            var preds = MonomialPass.Analyze(Spec);
            Assert.Equal(new[] { "Orient2d", "Orient3d", "InCircle" }, preds.Select(p => p.Name).ToArray());
            Assert.Equal(new[] { 2, 3, 4 }, preds.Select(p => p.Degree).ToArray());
            Assert.Equal(new[] { 6, 24, 48 }, preds.Select(p => p.Monomials.Count).ToArray());
            Assert.Equal(new[] { 66, 99, 132 }, preds.Select(p => p.Limbs(MonomialPass.MaxSpan)).ToArray());
            BigInteger m = (BigInteger.One << 53) - 1;
            foreach (var p in preds) {
                int d = p.Degree;
                BigInteger sum = p.Monomials.Count * BigInteger.Pow(m, d);
                for (int s = 0; s <= MonomialPass.MaxSpan; ++s) {
                    int limbs = p.Limbs(s);
                    // every monomial at the largest shift: the accumulator does not overflow
                    Assert.True((sum << (d * s)) < (BigInteger.One << (64 * limbs)), $"{p.Name}: span {s}");
                    // a monomial at the largest shift takes the limbs floor(d s / 64) .. floor(d s / 64) + d
                    Assert.True(d * s / 64 + d + 1 <= limbs, $"{p.Name}: span {s}");
                    // and no limb less would do at the limb boundary of the top monomial (the rule is not padded)
                    Assert.True(limbs <= d * s / 64 + d + 1, $"{p.Name}: span {s}");
                }
            }
        }

        // the monomials are the spec's formula: equal values at random integer inputs (exact), so the expansion and the
        // merge of like terms are right
        [Fact]
        public void Monomials_AreTheFormula()
        {
            var rnd = new Random(71);
            foreach (var p in MonomialPass.Analyze(Spec)) {
                for (int trial = 0; trial < 200; ++trial) {
                    var points = new Dictionary<string, (BigInteger x, BigInteger y, BigInteger w)>();
                    var values = new BigInteger[p.Inputs.Count];
                    int k = 0;
                    foreach (string pt in p.Source.Points) {
                        var c = new BigInteger[3];
                        for (int j = 0; j < p.Source.Comps.Length; ++j) values[k++] = c[j] = rnd.Next(-1000, 1001);
                        points[pt] = (c[0], c[1], c[2]);
                    }
                    BigInteger formula = PredicateCompiler.Evaluate(p.Source, points)[p.Source.Root];
                    BigInteger sum = 0;
                    foreach (var mono in p.Monomials) {
                        BigInteger t = mono.sign;
                        foreach (int i in mono.inputs) t *= values[i];
                        sum += t;
                    }
                    Assert.Equal(formula, sum);
                }
            }
        }

