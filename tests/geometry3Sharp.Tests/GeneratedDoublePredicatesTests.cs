                        Assert.Equal(Reference(kind, v), Kernel(kind, v));
                    }
                }
        }

        // The helper of one monomial against BigInteger: random mantissas with every bit used (the carries of the product
        // chain), exponents that put the monomial anywhere in the accumulator, and accumulators with limbs of all ones
        // above it (a carry that runs past the monomial's own limbs). The sign tests above would not see a wrong carry:
        // it changes a monomial far below the size of a determinant that is not degenerate.
        [Fact]
        public unsafe void AddHelpers_MatchBigInteger()
        {
            const int L = 16;
            var rnd = new Random(2026);
            ulong* p = stackalloc ulong[L], q = stackalloc ulong[L], m = stackalloc ulong[4];
            int* e = stackalloc int[4];
            byte[] buf = new byte[8];
            Func<ulong> next = () => { rnd.NextBytes(buf); return BitConverter.ToUInt64(buf, 0); };
            int longCarries = 0;
            for (int d = 2; d <= 4; ++d)
                for (int trial = 0; trial < 60000; ++trial) {
                    // accumulators: random low limbs, then a run of all ones in half of the trials, the top limbs zero
                    for (int i = 0; i < L; ++i) { p[i] = (i < L - 3) ? next() : 0; q[i] = (i < L - 3) ? next() : 0; }
                    bool ones = rnd.Next(2) == 0;
                    if (ones) for (int i = 1; i < L - 3; ++i) { p[i] = ulong.MaxValue; q[i] = ulong.MaxValue; }
                    ulong neg = 0;
                    int b = rnd.Next(-50, 50), off = -b;
                    for (int i = 0; i < d; ++i) {
                        int kind = rnd.Next(8);
                        m[i] = kind == 0 ? (1UL << 53) - 1 : kind == 1 ? 1UL << 52 : kind == 2 ? (ulong)rnd.Next(0, 3) : next() >> 11;
                        e[i] = rnd.Next(0, 60);
                        off += e[i];
                        if (rnd.Next(2) == 0) neg |= 1UL << i;
                    }
                    if (off < 0) { e[0] -= off; off = 0; }
                    bool minus = rnd.Next(2) == 0;
                    BigInteger P = ToBig(p, L), Q = ToBig(q, L), product = BigInteger.One;
                    int negatives = minus ? 1 : 0;
                    for (int i = 0; i < d; ++i) { product *= m[i]; if (((neg >> i) & 1) != 0) negatives++; }
                    if (negatives % 2 == 0) P += product << off; else Q += product << off;
                    Add(d, p, q, L, m, e, neg, b, minus);
                    Assert.True(P == ToBig(p, L) && Q == ToBig(q, L), $"add{d}, trial {trial}");
                    if (ones && !product.IsZero && (p[L - 3] != 0 || q[L - 3] != 0)) longCarries++;
                }
            // the carry beyond the monomial's limbs ran (through the limbs of all ones into the first zero limb)
            Assert.True(longCarries > 1000, $"{longCarries} long carries");
        }

        static unsafe void Add(int d, ulong* p, ulong* q, int limbs, ulong* m, int* e, ulong neg, int b, bool minus)
        {
            if (d == 2) DoublePredicates.add2(p, q, limbs, m, e, neg, b, 0, 1, minus);
            else if (d == 3) DoublePredicates.add3(p, q, limbs, m, e, neg, b, 0, 1, 2, minus);
            else DoublePredicates.add4(p, q, limbs, m, e, neg, b, 0, 1, 2, 3, minus);
        }

        // A monomial or a carry that would leave the accumulator throws and writes nothing outside it (the limb rule
        // excludes it; the check makes an error of the rule, of the generator or of a caller an exception instead of a
        // write outside the stack buffer): one limb too few for the shifted monomial, a carry that runs out of the top
        // limb, and an offset below the accumulator (the exponent base above the monomial's exponents).
        [Fact]
        public unsafe void AddHelpers_ThrowOutsideTheAccumulator()
        {
            const int L = 12, Guard = 4;
            const ulong Canary = 0xC0FFEE0DDF00D123UL;
            ulong* buf = stackalloc ulong[2 * (L + Guard) + Guard], m = stackalloc ulong[4];
            int* e = stackalloc int[4];
            for (int d = 2; d <= 4; ++d)
                foreach (string what in new[] { "fits", "one limb short", "carry out of the top", "offset below" })
                    foreach (bool negative in new[] { false, true }) {
                        // p and q with canaries below, between and above
                        for (int i = 0; i < 2 * (L + Guard) + Guard; ++i) buf[i] = Canary;
                        ulong* p = buf + Guard, q = p + L + Guard;
                        for (int i = 0; i < d; ++i) { m[i] = (1UL << 53) - 1; e[i] = 64; }
                        // the monomial at limb w = d, shifted by 13 bits: limbs d .. 2 d
                        int b = 0;
                        e[0] += 13;
                        int limbs = what == "one limb short" ? 2 * d : 2 * d + 1;
                        for (int i = 0; i < limbs; ++i) { p[i] = 0; q[i] = 0; }
                        if (what == "carry out of the top") for (int i = 0; i < limbs; ++i) { p[i] = ulong.MaxValue; q[i] = ulong.MaxValue; }
                        if (what == "offset below") b = 64 * d + 13 + 1;
                        ulong neg = negative ? 1UL : 0UL;
                        string thrown = null;
                        try { Add(d, p, q, limbs, m, e, neg, b, false); } catch (InvalidOperationException ex) { thrown = ex.Message; }
                        // (the message says which of the two checks fired)
                        string expected = what == "fits" ? null : what == "carry out of the top" ? "a carry outside its accumulator" : "a monomial outside its accumulator";
                        Assert.True(expected == null ? thrown == null : thrown != null && thrown.Contains(expected), $"add{d}, {what}, negative {negative}: thrown {thrown}");
                        // nothing outside the two accumulators was written
                        for (int i = 0; i < Guard; ++i) {
                            Assert.True(buf[i] == Canary && p[limbs + i] == Canary && q[limbs + i] == Canary, $"add{d}, {what}, negative {negative}: a limb outside");
                        }
                        // and the other accumulator is untouched
                        ulong* other = negative ? p : q;
                        for (int i = 0; i < limbs; ++i)
                            Assert.True(other[i] == (what == "carry out of the top" ? ulong.MaxValue : 0UL), $"add{d}, {what}, negative {negative}: the other accumulator");
                        if (what == "fits") Assert.True((negative ? q : p)[2 * d] != 0 || (negative ? q : p)[2 * d - 1] != 0, "the monomial reaches the top limbs");
                    }
        }

        static unsafe BigInteger ToBig(ulong* limbs, int n)
        {
            BigInteger v = BigInteger.Zero;
            for (int i = n - 1; i >= 0; --i) v = (v << 64) + limbs[i];
            return v;
        }

