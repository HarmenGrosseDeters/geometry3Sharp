        [Fact]
        public void EdgePinch_IsSeparated_AndTheResultIsClean()
        {
            var without = new SolidBooleanPipeline(EdgePinch(Vector3d.Zero), D);
            Assert.True(without.Compute(), without.Error);
            Assert.True(SolidBooleanPipeline.SelfContacts(without.Result).Count > 0);
            Assert.NotEqual("", without.Report.NotCleanReason);         // (the contact counts as a self-intersection)

            var p = new SolidBooleanPipeline(EdgePinch(Vector3d.Zero), D) { SeparateSelfContacts = 1e-3 };
            Assert.True(p.Compute(), p.Error);
            AssertSolid(p);
            Assert.Equal(SolidBooleanPipeline.SelfContacts(without.Result).Count, p.Report.SelfContactsFound);
            Assert.Equal(0, p.Report.SelfContactsLeft);
            Assert.Empty(SolidBooleanPipeline.SelfContacts(p.Result));
            Assert.True(p.Report.SelfContactVerticesMoved > 0);
            Assert.True(p.Report.SelfContactMaxMove > 0 && p.Report.SelfContactMaxMove <= 1e-3 * (1 + 1e-12));
            Assert.Equal(0, p.Report.ContactsResult);
            Assert.True(p.Report.Clean, p.Report.NotCleanReason);
            // the volume: within the moved distance times the area around the moved vertices (here far less than the plate's area)
            Assert.True(Math.Abs(Volume(p.Result) - Volume(without.Result)) <= 1e-3 * 16, Volume(p.Result) + " vs " + Volume(without.Result));
            Assert.Equal(without.Result.TriangleCount, p.Result.TriangleCount);
        }

