        static DMesh3 FromArrays(double[] v, int[] t)
        {
            var m = new DMesh3();
            for (int i = 0; i < v.Length; i += 3)
                m.AppendVertex(new Vector3d(v[i], v[i + 1], v[i + 2]));
            for (int i = 0; i < t.Length; i += 3)
                m.AppendTriangle(t[i], t[i + 1], t[i + 2]);
            return m;
        }

        static List<DMesh3> PointPinch()
