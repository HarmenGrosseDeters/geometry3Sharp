            Assert.True(p.Report.Clean, p.Report.NotCleanReason);
            double v0 = Volume(without.Result);
            Assert.True(Math.Abs(Volume(p.Result) - v0) <= 1e-9 * Math.Abs(v0), Volume(p.Result) + " vs " + v0);
        }

