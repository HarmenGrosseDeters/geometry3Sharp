            var without = new SolidBooleanPipeline(inputs, D) { InputGrid = 1.0 / (1 << 20) };
            Assert.True(without.Compute(), without.Error);
            Assert.Equal(5, SolidBooleanPipeline.SelfContacts(without.Result).Count);
            var p = new SolidBooleanPipeline(inputs, D) { InputGrid = 1.0 / (1 << 20), SeparateSelfContacts = 1e-6 };
            Assert.True(p.Compute(), p.Error);
            AssertSolid(p);
            Assert.Equal(5, p.Report.SelfContactsFound);
            Assert.Equal(0, p.Report.SelfContactsLeft);
            Assert.True(p.Report.SelfContactMovesUndoneCrossing > 0);
            Assert.True(p.Report.SelfContactMovesUndoneFlipped > 0);
            Assert.True(p.Report.SelfContactVerticesMoved >= 5);      // (at least one vertex of each contact)
            Assert.Equal(0, p.Report.ContactsResult);
            Assert.True(p.Report.Clean, p.Report.NotCleanReason);
            double v0 = Volume(without.Result);
            Assert.True(Math.Abs(Volume(p.Result) - v0) <= 1e-9 * Math.Abs(v0), Volume(p.Result) + " vs " + v0);
        }

