        [Theory]
        [MemberData(nameof(FrameNames))]
        public void Separation_IsInvariantUnderSimilarities(string frame)
        {
            Similarity s = Similarity.ByName(frame);
            var reference = new SolidBooleanPipeline(EdgePinch(Vector3d.Zero), D) { SeparateSelfContacts = 1e-3 };
            Assert.True(reference.Compute(), reference.Error);
            var p = new SolidBooleanPipeline(EdgePinch(Vector3d.Zero).Select(m => Invariance.Transformed(m, s)).ToList(), D) { SeparateSelfContacts = 1e-3 * s.Scale };
            Assert.True(p.Compute(), s.Name + ": " + p.Error);
            AssertSolid(p);
            Assert.Equal(reference.Report.SelfContactsFound, p.Report.SelfContactsFound);
            Assert.Equal(0, p.Report.SelfContactsLeft);
            Assert.True(p.Report.Clean, s.Name + ": " + p.Report.NotCleanReason);
            if (s.IsExact)
                Assert.Equal("", Invariance.Difference(reference.Result, Invariance.MappedBack(p.Result, s)));
        }

