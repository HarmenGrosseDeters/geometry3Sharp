                Assert.Equal(O_Dist3(sel(new[] { 0, 1, 2, 3, 4, 5, 6 })), BisectorPredicates.DistanceAbove3Big(E[0], E[1], E[2], E[3], E[4], E[5], E[6]));
                Assert.Equal(O_RadiusEdge(sel(new[] { 0, 1, 2, 3, 4, 5 })), path(() => BisectorPredicates.RadiusEdgeAbove(ref f[0], ref f[1], ref f[2], ref f[3], ref f[4], ref f[5])));
                Assert.Equal(O_RadiusEdge(sel(new[] { 0, 1, 2, 3, 4, 5 })), BisectorPredicates.RadiusEdgeAboveBig(E[0], E[1], E[2], E[3], E[4], E[5]));
            }
            Assert.True(fixedPath > 100 && bigPath > 20, $"fixed {fixedPath}, big {bigPath}");
        }

        // ---- the calls: the entry, its filter (never wrong where it decides) and its exact stage ----

        static int filterDecided, filterCalls;
        const int NotInRange = int.MinValue;      // the filter was not called (an input outside its range)

        static int Check(int oracle, int entry, int filter, int exact, string what)
        {
            Assert.True(oracle == exact, what + ": exact " + exact + " != oracle " + oracle);
            Assert.True(oracle == entry, what + ": entry " + entry + " != oracle " + oracle);
            if (filter == NotInRange) return entry;
            filterCalls++;
            if (filter != 2) { filterDecided++; Assert.True(filter == oracle, what + ": the filter is wrong"); }
            return entry;
        }

        internal static int Side1(Vector3d v, Vector3d a, Vector3d e) => Check(O_Side1(v, a, e), BisectorPredicates.BisectorSide1(v, a, e),
            Gate(2, v, a, e) ? BisectorPredicates.BisectorSide1Filter(v, a, e) : NotInRange, BisectorPredicates.BisectorSide1Exact(v, a, e), "Side1");

        internal static int Side2(Vector3d q0, Vector3d q1, Vector3d a, Vector3d b, Vector3d c) => Check(O_Side2(q0, q1, a, b, c),
            BisectorPredicates.BisectorSide2(q0, q1, a, b, c), Gate(4, q0, q1, a, b, c) ? BisectorPredicates.BisectorSide2Filter(q0, q1, a, b, c) : NotInRange,
            BisectorPredicates.BisectorSide2Exact(q0, q1, a, b, c), "Side2");

        internal static int Side3(Vector3d a, Vector3d b, Vector3d c, Vector3d t0, Vector3d t1, Vector3d t2, Vector3d e)
        {
            int r = Check(O_Side3(a, b, c, t0, t1, t2, e), BisectorPredicates.BisectorSide3(a, b, c, t0, t1, t2, e),
                Gate(6, a, b, c, t0, t1, t2, e) ? BisectorPredicates.BisectorSide3Filter(a, b, c, t0, t1, t2, e) : NotInRange,
                BisectorPredicates.BisectorSide3Exact(a, b, c, t0, t1, t2, e), "Side3");
            // the prepared form gives the same sign
            BisectorPredicates.BisectorSide3Prepare(a, b, c, t0, t1, t2, out var s);
            Assert.Equal(r, BisectorPredicates.BisectorSide3(ref s, e));
            return r;
        }

        internal static int DotS(Vector3d o, Vector3d p, Vector3d q0, Vector3d q1) => Check(O_DotSites(o, p, q0, q1),
            BisectorPredicates.DotSites(o, p, q0, q1), Gate(2, o, p, q0, q1) ? BisectorPredicates.DotSitesFilter(o, p, q0, q1) : NotInRange,
            BisectorPredicates.DotSitesExact(o, p, q0, q1), "DotSites");

        internal static int DetN(Vector3d o, Vector3d p, Vector3d q, Vector3d t0, Vector3d t1, Vector3d t2) => Check(O_DetSitesNormal(o, p, q, t0, t1, t2),
            BisectorPredicates.DetSitesNormal(o, p, q, t0, t1, t2), Gate(4, o, p, q, t0, t1, t2) ? BisectorPredicates.DetSitesNormalFilter(o, p, q, t0, t1, t2) : NotInRange,
            BisectorPredicates.DetSitesNormalExact(o, p, q, t0, t1, t2), "DetSitesNormal");

        static int Dist1(Vector3d v, Vector3d a, double r)
        {
            var R = new Vector3d(r, 0, 0);
            return Check(O_Dist1(v, a, r), BisectorPredicates.DistanceAbove1(v, a, R), Gate(2, v, a, R) ? BisectorPredicates.DistanceAbove1Filter(v, a, R) : NotInRange,
                BisectorPredicates.DistanceAbove1Exact(v, a, R), "Dist1");
        }

        static int Dist2(Vector3d q0, Vector3d q1, Vector3d a, Vector3d b, double r)
        {
            var R = new Vector3d(r, 0, 0);
            return Check(O_Dist2(q0, q1, a, b, r), BisectorPredicates.DistanceAbove2(q0, q1, a, b, R),
                Gate(6, q0, q1, a, b, R) ? BisectorPredicates.DistanceAbove2Filter(q0, q1, a, b, R) : NotInRange,
                BisectorPredicates.DistanceAbove2Exact(q0, q1, a, b, R), "Dist2");
        }

        static int Dist3(Vector3d a, Vector3d b, Vector3d c, Vector3d t0, Vector3d t1, Vector3d t2, double r)
        {
            var R = new Vector3d(r, 0, 0);
            return Check(O_Dist3(a, b, c, t0, t1, t2, r), BisectorPredicates.DistanceAbove3(a, b, c, t0, t1, t2, R),
                Gate(10, a, b, c, t0, t1, t2, R) ? BisectorPredicates.DistanceAbove3Filter(a, b, c, t0, t1, t2, R) : NotInRange,
                BisectorPredicates.DistanceAbove3Exact(a, b, c, t0, t1, t2, R), "Dist3");
        }

        static int RadiusEdge(Vector3d a, Vector3d b, Vector3d c, Vector3d p, Vector3d q, Vector3d k) => Check(O_RadiusEdge(a, b, c, p, q, k),
            BisectorPredicates.RadiusEdgeAbove(a, b, c, p, q, k), Gate(7, a, b, c, p, q, k) ? BisectorPredicates.RadiusEdgeAboveFilter(a, b, c, p, q, k) : NotInRange,
            BisectorPredicates.RadiusEdgeAboveExact(a, b, c, p, q, k), "RadiusEdge");

        // the filter's range for a predicate of the degree (Compiler.cs filter_bounds: [2^-(960 / degree - 52), 2^high]); the
        // generated entry tests it itself, here only to call the filter where it is defined (a conservative upper end)
        static bool Gate(int degree, params Vector3d[] P)
        {
            double lo = ScaleB(1.0, -(960 / degree - 52)), hi = ScaleB(1.0, 1000 / degree - 10);
            foreach (var p in P)
                foreach (double x in new[] { p.x, p.y, p.z })
                    if (x != 0 && !(Math.Abs(x) >= lo && Math.Abs(x) <= hi)) return false;
            return true;
        }

        // ---- inputs ----

        static Vector3d RandomPoint(Random rand, int bits, int exp)
        {
            Func<double> c = () => ScaleB(rand.Next(2) == 0 ? NextBits(rand, bits) : -NextBits(rand, bits), exp);
            return new Vector3d(c(), c(), c());
        }

        static Vector3d[] RandomPoints(Random rand, int n, int bits, int exp, bool spread)
        {
            // spread: each point at its own exponent (the exact stage then aligns them; beyond two limbs: BigInteger)
            return Enumerable.Range(0, n).Select(_ => RandomPoint(rand, bits, spread ? exp + rand.Next(-60, 61) : exp)).ToArray();
        }

        /// <summary> every predicate equals the oracle on random inputs: small grids, full mantissas, wide exponent spans, every sign </summary>
        [Fact]
        public void Predicates_MatchTheOracle_AtAllSizes()
        {
            var rand = new Random(1);
            filterDecided = filterCalls = 0;
            var seen = new HashSet<(string, int)>();
            for (int k = 0; k < 1500; ++k) {
                int bits = new[] { 3, 10, 30, 53 }[k % 4];
                int exp = new[] { 0, -40, 40, -300, 300 }[(k / 4) % 5];
                bool spread = k % 7 == 3;
                var P = RandomPoints(rand, 7, bits, exp, spread);
                double r = Math.Abs(P[6].x) + ScaleB(1.0, exp);
                seen.Add(("s1", Side1(P[0], P[1], P[2])));
                seen.Add(("s2", Side2(P[0], P[1], P[2], P[3], P[4])));
                seen.Add(("s3", Side3(P[0], P[1], P[2], P[3], P[4], P[5], P[6])));
                seen.Add(("dot", DotS(P[0], P[1], P[2], P[3])));
                seen.Add(("det", DetN(P[0], P[1], P[2], P[3], P[4], P[5])));
                seen.Add(("d1", Dist1(P[0], P[1], r)));
                seen.Add(("d2", Dist2(P[0], P[1], P[2], P[3], r)));
                seen.Add(("d3", Dist3(P[0], P[1], P[2], P[3], P[4], P[5], r)));
                seen.Add(("re", RadiusEdge(P[0], P[1], P[2], P[0], P[1], new Vector3d(rand.NextDouble() * 4, 1, 0))));
            }
            foreach (var n in new[] { "s1", "s2", "s3", "dot", "det", "d1", "d2", "d3", "re" }) {
                Assert.Contains((n, 1), seen);
                Assert.Contains((n, -1), seen);
            }
            // (in its range the filter decides almost every random input)
            Assert.True(filterCalls > 5000 && filterDecided > 0.97 * filterCalls, $"the filter decided {filterDecided} of {filterCalls}");
        }

        // integer vectors of length 3 (the sites of the exact zeros: equidistant from a point)
        static readonly Vector3d[] Norm3 = new[] { new Vector3d(1, 2, 2), new Vector3d(2, -1, 2), new Vector3d(-2, 2, 1), new Vector3d(3, 0, 0),
            new Vector3d(0, -3, 0), new Vector3d(0, 0, 3), new Vector3d(-1, -2, 2), new Vector3d(2, 2, -1), new Vector3d(-2, -1, -2) };

        /// <summary>
        /// exact zeros: a vertex on a bisector, an edge crossing at a point equidistant from three sites, a Voronoi vertex on a
        /// triangle's plane, the distance exactly r, a right triangle at rho = 1/2; nearby perturbations get the signs; also a
        /// point that does not exist (an edge parallel to the bisector, a Voronoi line parallel to the plane)
        /// </summary>
        [Fact]
        public void Predicates_ExactZeros()
        {
            var rand = new Random(2);
            for (int k = 0; k < 400; ++k) {
                double s = ScaleB(1.0, rand.Next(-200, 200));
                var x = new Vector3d(rand.Next(-50, 50), rand.Next(-50, 50), rand.Next(-50, 50));
                var sites = Norm3.OrderBy(_ => rand.Next()).Take(4).Select(d => (x + d) * s).ToArray();
                Vector3d a = sites[0], b = sites[1], c = sites[2], e = sites[3], X = x * s;
                // a mesh vertex equidistant from a and e
                Assert.Equal(0, Side1(X, a, e));
                Assert.Equal(0, Dist1(X, a, 3 * s));
                Assert.Equal(1, Dist1(X, a, 3 * s * (1 - 1e-15)));
                Assert.Equal(-1, Dist1(X, a, 3 * s * (1 + 1e-15)));
                // a mesh edge through X, crossing bisector(a, b) at X
                var dir = new Vector3d(rand.Next(-9, 10), rand.Next(-9, 10), rand.Next(-9, 10));
                Vector3d q0 = X - dir * s, q1 = X + dir * s;
                int dS = DotS(a, b, q0, q1);
                Assert.Equal(0, Side2(q0, q1, a, b, c));           // (0 also where the edge is parallel, dS = 0)
                Assert.Equal(0, Dist2(q0, q1, a, b, 3 * s));
                // a triangle through X: X = BTPI(a, b, c; t)
                Vector3d u = new Vector3d(rand.Next(-9, 10), rand.Next(-9, 10), rand.Next(-9, 10)) * s, w = new Vector3d(rand.Next(-9, 10), rand.Next(-9, 10), rand.Next(-9, 10)) * s;
                Vector3d t0 = X + u, t1 = X + w, t2 = X - u - w;
                Assert.Equal(0, Side3(a, b, c, t0, t1, t2, e));
                Assert.Equal(0, Dist3(a, b, c, t0, t1, t2, 3 * s));
                // e moved off the sphere: the signs follow the distance (closer to e when e moves towards X)
                Vector3d eIn = X + (e - X) * 0.75, eOut = X + (e - X) * 1.25;
                if (DetN(a, b, c, t0, t1, t2) != 0) {
                    Assert.Equal(1, Side3(a, b, c, t0, t1, t2, eIn));
                    Assert.Equal(-1, Side3(a, b, c, t0, t1, t2, eOut));
                } else
                    Assert.Equal(0, Side3(a, b, c, t0, t1, t2, eIn));
                if (dS != 0) {
                    Assert.Equal(1, Side2(q0, q1, a, b, X + (c - X) * 0.75));
                    Assert.Equal(-1, Side2(q0, q1, a, b, X + (c - X) * 1.25));
                }
                Assert.Equal(1, Side1(X, a, eIn));
                Assert.Equal(-1, Side1(X, a, eOut));
                // parallel: an edge in the bisector plane's direction, a triangle containing the Voronoi line's direction
                var m = (a + b) * 0.5;
                var along = new Vector3d(b.y - a.y, a.x - b.x, 0);
                if (along.LengthSquared > 0) {
                    Assert.Equal(0, DotS(a, b, m, m + along));
                    Assert.Equal(0, Side2(m, m + along, a, b, c));
                    Assert.Equal(0, Dist2(m, m + along, a, b, s));
                }
                // the coefficient predicates at their zeros
                Assert.Equal(0, DetN(a, b, b, t0, t1, t2));
                Assert.Equal(0, DetN(a, b, c, t0, t0, t2));
                // a right triangle: R = hypotenuse / 2, so R = rho |hyp| at rho^2 = 1/4, below at 1/4 + eps, above at 1/4 - eps
                Vector3d ra = X, rb = X + new Vector3d(3, 0, 0) * s, rc = X + new Vector3d(0, 4, 0) * s;
                Assert.Equal(0, RadiusEdge(ra, rb, rc, rb, rc, new Vector3d(0.25, 1, 0)));
                Assert.Equal(1, RadiusEdge(ra, rb, rc, rb, rc, new Vector3d(0.25 * (1 - 1e-15), 1, 0)));
                Assert.Equal(-1, RadiusEdge(ra, rb, rc, rb, rc, new Vector3d(0.25 * (1 + 1e-15), 1, 0)));
            }
        }

        /// <summary>
        /// the three paths of the double entry: the filter (in its range), FixedArith (aligned within two limbs: no allocation),
        /// BigInteger (beyond: wide exponent spans, subnormals); all equal to the oracle; zeros and non-finite inputs
        /// </summary>
        [Fact]
        public void DoubleEntry_Paths_Gate_Subnormals()
        {
            var rand = new Random(3);
            for (int k = 0; k < 300; ++k) {
                var P = RandomPoints(rand, 7, 53, 0, false);
                // one point far outside the filter's range of the degree-10 predicate (2^-44 .. 2^97), another subnormal
                if (k % 3 == 0) P[k % 7] = P[k % 7] * ScaleB(1.0, rand.Next(2) == 0 ? -200 : 200);
                if (k % 5 == 1) P[(k + 3) % 7] = new Vector3d(double.Epsilon * rand.Next(1, 1000), 0, -double.Epsilon * 3);
                double r = Math.Abs(P[6].x) + 1;
                Side1(P[0], P[1], P[2]);
                Side2(P[0], P[1], P[2], P[3], P[4]);
                Side3(P[0], P[1], P[2], P[3], P[4], P[5], P[6]);
                DotS(P[0], P[1], P[2], P[3]);
                DetN(P[0], P[1], P[2], P[3], P[4], P[5]);
                Dist1(P[0], P[1], r);
                Dist2(P[0], P[1], P[2], P[3], r);
                Dist3(P[0], P[1], P[2], P[3], P[4], P[5], r);
                RadiusEdge(P[0], P[1], P[2], P[1], P[2], new Vector3d(1, 1, 0));
            }
            // all zero, and not finite
            var z = Vector3d.Zero;
            Assert.Equal(0, BisectorPredicates.BisectorSide3(z, z, z, z, z, z, z));
            Assert.Equal(0, BisectorPredicates.DistanceAbove1(z, z, z));
            Assert.Throws<ArgumentException>(() => BisectorPredicates.BisectorSide1(new Vector3d(double.NaN, 0, 0), z, z));
            Assert.Throws<ArgumentException>(() => BisectorPredicates.DistanceAbove3(z, z, z, z, z, new Vector3d(0, double.PositiveInfinity, 0), z));
#if NET
            // the FixedArith path allocates nothing (inputs within two limbs after aligning)
            var Q = RandomPoints(rand, 7, 53, 0, false);
            BisectorPredicates.BisectorSide3Exact(Q[0], Q[1], Q[2], Q[3], Q[4], Q[5], Q[6]);
            BisectorPredicates.DistanceAbove3Exact(Q[0], Q[1], Q[2], Q[3], Q[4], Q[5], Q[6]);
            long before = GC.GetAllocatedBytesForCurrentThread();
            BisectorPredicates.BisectorSide3Exact(Q[0], Q[1], Q[2], Q[3], Q[4], Q[5], Q[6]);
            BisectorPredicates.DistanceAbove3Exact(Q[0], Q[1], Q[2], Q[3], Q[4], Q[5], Q[6]);
            Assert.Equal(0, GC.GetAllocatedBytesForCurrentThread() - before);
#endif
        }

        /// <summary> nearly degenerate inputs (a zero moved by one ulp): the filter refuses or is right, the entry is exact </summary>
        [Fact]
        public void Filter_NearlyDegenerate_NeverWrong()
        {
            var rand = new Random(4);
            filterDecided = filterCalls = 0;
            for (int k = 0; k < 600; ++k) {
                double s = ScaleB(1.0, rand.Next(-30, 30));
                var x = new Vector3d(rand.Next(-1000, 1000), rand.Next(-1000, 1000), rand.Next(-1000, 1000));
                var sites = Norm3.OrderBy(_ => rand.Next()).Take(4).Select(d => (x + d * 1000) * s).ToArray();
                Func<Vector3d, Vector3d> ulp = p => new Vector3d(rand.Next(3) == 0 ? BitIncrement(p.x) : p.x,
                    rand.Next(3) == 0 ? BitDecrement(p.y) : p.y, rand.Next(3) == 0 ? BitIncrement(p.z) : p.z);
                Vector3d X = x * s, u = new Vector3d(rand.Next(-90, 91), rand.Next(-90, 91), rand.Next(-90, 91)) * s,
                    w = new Vector3d(rand.Next(-90, 91), rand.Next(-90, 91), rand.Next(-90, 91)) * s;
                Side1(ulp(X), sites[0], sites[3]);
                Side2(ulp(X - u), X + u, sites[0], sites[1], ulp(sites[2]));
                Side3(sites[0], sites[1], sites[2], ulp(X + u), X + w, X - u - w, ulp(sites[3]));
                Dist1(ulp(X), sites[0], 3000 * s);
                Dist2(ulp(X - u), X + u, sites[0], sites[1], 3000 * s);
                Dist3(sites[0], sites[1], ulp(sites[2]), X + u, X + w, X - u - w, 3000 * s);
            }
            Assert.True(filterCalls > 0);
        }

        /// <summary>
        /// 2^k scaling keeps every sign (homogeneous formulas, exact in floating point); the similarities of the harness move
        /// the points off the grid, so there the oracle is the reference
        /// </summary>
        [Fact]
        public void Invariance_UnderTheHarnessSimilarities()
        {
            var rand = new Random(6);
            int zeros = 0;
            for (int k = 0; k < 120; ++k) {
                // the layout: X, the sites a, b, c, e, an edge q0 q1, a triangle t0 t1 t2, a right triangle r0 r1 r2
                Vector3d[] P;
                if (k % 3 == 0) {
                    // exact zeros of every predicate that a 2^k scaling keeps: the sites at distance 3 from X, the edge and
                    // the triangle through X, the right triangle at rho^2 = 1/4 against its hypotenuse
                    var x = new Vector3d(rand.Next(-50, 50), rand.Next(-50, 50), rand.Next(-50, 50));
                    var S = Norm3.OrderBy(_ => rand.Next()).Take(4).ToArray();
                    var dir = new Vector3d(rand.Next(-9, 10), rand.Next(-9, 10), rand.Next(-9, 10));
                    Vector3d u = new Vector3d(1, 2, 0), w = new Vector3d(0, 1, 3);
                    P = new[] { x, x + S[0], x + S[1], x + S[2], x + S[3], x - dir, x + dir, x + u, x + w, x - u - w,
                        x, x + new Vector3d(3, 0, 0), x + new Vector3d(0, 4, 0) };
                } else
                    P = RandomPoints(rand, 13, 20, -10, false);
                Func<Vector3d[], double, int[]> all = (Q, sc) => new[] {
                    Side1(Q[0], Q[1], Q[4]), Side2(Q[5], Q[6], Q[1], Q[2], Q[3]), Side3(Q[1], Q[2], Q[3], Q[7], Q[8], Q[9], Q[4]),
                    Dist1(Q[0], Q[1], 3 * sc), Dist2(Q[5], Q[6], Q[1], Q[2], 3 * sc), Dist3(Q[1], Q[2], Q[3], Q[7], Q[8], Q[9], 3 * sc),
                    RadiusEdge(Q[10], Q[11], Q[12], Q[11], Q[12], new Vector3d(0.25, 1, 0)) };
                int[] reference = all(P, 1);
                if (k % 3 == 0) {
                    Assert.Equal(0, reference[0]);
                    Assert.Equal(0, reference[3]);
                    Assert.Equal(0, reference[6]);
                    zeros += reference.Count(v => v == 0);
                }
                foreach (var sim in Similarity.All()) {
                    var Q = P.Select(sim.Apply).ToArray();
                    int[] got = all(Q, sim.Scale);      // equal to the oracle (Check), whatever the similarity did to the zeros
                    if (sim.IsExact) Assert.Equal(reference, got);
                }
            }
            Assert.True(zeros > 200, "zeros " + zeros);
        }
