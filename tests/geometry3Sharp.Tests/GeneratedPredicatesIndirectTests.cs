        /// <summary>
        /// the orientation convention is the library's: Orient3dLPI(..., a, b, c) = ExactPredicates.Orient3d(a, b, c, x)
        /// for an LPI point x with integer coordinates (and likewise TPI)
        /// </summary>
        [Fact]
        public void Convention_IsExactPredicatesOrient3d()
        {
            var rand = new Random(9);
            Func<int, ExactPoint3> pt = r => ExactPoint3.FromInteger(rand.Next(-r, r), rand.Next(-r, r), rand.Next(-r, r));
            Func<ExactPoint3, Vector3d> vec = p => new Vector3d((double)p.X, (double)p.Y, (double)p.Z);
            int nonzero = 0;
            for (int k = 0; k < 500; ++k) {
                // the line through x0 and x0 + e (x0 an integer point on the plane z = h through r, s, t): LPI = x0
                long h = rand.Next(-50, 50);
                var x0 = ExactPoint3.FromInteger(rand.Next(-50, 50), rand.Next(-50, 50), h);
                ExactPoint3 r = ExactPoint3.FromInteger(rand.Next(-50, 50), rand.Next(-50, 50), h), s = ExactPoint3.FromInteger(rand.Next(-50, 50), rand.Next(-50, 50), h),
                    t = ExactPoint3.FromInteger(rand.Next(-50, 50), rand.Next(-50, 50), h);
                var p = ExactPoint3.FromInteger(x0.X + 3, x0.Y - 2, x0.Z + 5);
                var q = ExactPoint3.FromInteger(x0.X - 6, x0.Y + 4, x0.Z - 10);
                ExactPoint3 a = pt(100), b = pt(100), c = pt(100);
                int expected = OracleLPI(new[] { p, q, r, s, t, a, b, c });
                int lpi = LPI(new[] { p, q, r, s, t, a, b, c });
                // a degenerate plane r, s, t (collinear) has no point: d = 0 and the predicate 0
                if (ExactPredicates.Orient2d(new Vector2d((double)r.X, (double)r.Y), new Vector2d((double)s.X, (double)s.Y), new Vector2d((double)t.X, (double)t.Y)) == 0) {
                    Assert.Equal(0, lpi);
                    continue;
                }
                Assert.Equal(ExactPredicates.Orient3d(vec(a), vec(b), vec(c), vec(x0)), lpi);
                Assert.Equal(expected, lpi);
                if (lpi != 0) nonzero++;
                // TPI of the planes z = h (r, s, t), x = x0.X and y = x0.Y (axis-parallel triangles through x0)
                var P = new[] { r, s, t,
                    x0, ExactPoint3.FromInteger(x0.X, x0.Y + 1, x0.Z), ExactPoint3.FromInteger(x0.X, x0.Y, x0.Z + 1),
                    x0, ExactPoint3.FromInteger(x0.X + 1, x0.Y, x0.Z), ExactPoint3.FromInteger(x0.X, x0.Y, x0.Z + 1), a, b, c };
                Assert.Equal(ExactPredicates.Orient3d(vec(a), vec(b), vec(c), vec(x0)), TPI(P));
            }
            Assert.True(nonzero > 400);
        }


